#!/usr/bin/env python3
"""Write src/nmath.rs: Rmath.h's exported names (Rf_dnorm4, Rf_pgamma, ...)
over robigo-numerics, whose functions port GNU R's nmath. Rmath.h maps each
name to its export; numerics' signatures give the argument types (bool
for give_log/lower_tail/log_p, which C passes as int).

  crates/robigo-capi/gen-nmath.py
"""
import os, re, glob

HERE = os.path.dirname(os.path.abspath(__file__))
RSRC = os.path.expanduser("~/.cache/robigo-research/rsrc/R-4.5.0")
NUM = os.path.join(HERE, "..", "robigo-numerics", "src")

rmath = open(os.path.join(RSRC, "src/include/Rmath.h0.in")).read()
# '#define dnorm dnorm4' then '#define dnorm4 Rf_dnorm4'
alias = dict(re.findall(r'#define\s+([a-z_0-9]+)\s+([a-z_0-9]+)\s*$', rmath, re.M))
export = dict(re.findall(r'#define\s+([a-z_0-9]+)\s+(Rf_[a-z_0-9]+)', rmath))

sigs = {}
for f in sorted(glob.glob(os.path.join(NUM, "*.rs"))):
    mod = os.path.basename(f)[:-3]
    for m in re.finditer(r'^pub fn ([a-z_0-9]+)\(([^)]*)\)\s*->\s*(f64|i32)', open(f).read(), re.M):
        name, args, ret = m.groups()
        if name in sigs:
            continue
        parts = [a.strip() for a in args.split(",") if a.strip()]
        types = []
        ok = True
        for p in parts:
            p = p[4:] if p.startswith("mut ") else p
            n, t = [x.strip() for x in p.split(":", 1)]
            if t in ("f64", "bool", "i32"):
                types.append(t)
            elif t == "&mut Rng":
                types.append("rng")
            else:
                ok = False
        if ok:
            sigs[name] = (mod, types, ret)

out = ['//! Generated by crates/robigo-capi/gen-nmath.py: Rmath.h\'s exports over',
       '//! robigo-numerics (GNU R\'s nmath, ported). Random variates use the',
       '//! host\'s generator, as GNU R\'s use RNG.c\'s state.', '',
       '#![allow(clippy::all)]', '', 'use std::ffi::c_int;', '']
done = set()
for short, rf in sorted(export.items()):
    base = short
    # Rmath.h's '#define dnorm dnorm4': the numerics name is the user-level one
    users = [u for u, a in alias.items() if a == short]
    cand = [short] + users + [short.rstrip("0123456789")]
    hit = next((c for c in cand if c in sigs), None)
    if hit is None or rf in done:
        continue
    mod, types, ret = sigs[hit]
    params, call = [], []
    for k, t in enumerate(types):
        if t == "rng":
            call.append("rng")
            continue
        ct = {"f64": "f64", "bool": "c_int", "i32": "c_int"}[t]
        params.append(f"a{k}: {ct}")
        call.append(f"a{k} != 0" if t == "bool" else f"a{k}")
    path = "robigo_numerics" if mod == "lib" else f"robigo_numerics::{mod}"
    body = f"{path}::{hit}({', '.join(call)})"
    if "rng" in types:
        body = f"crate::rng::with_rng(|rng| {body})"
    rty = "f64" if ret == "f64" else "c_int"
    # nmath's MATHLIB_WARNINGs, which numerics queues, are R warnings now
    out.append(f"#[unsafe(no_mangle)]\npub extern \"C\" fn {rf}({', '.join(params)}) -> {rty} {{\n    let r = {body};\n    crate::errors::nmath_warnings();\n    r\n}}\n")
    done.add(rf)
open(os.path.join(HERE, "src", "nmath.rs"), "w").write("\n".join(out))
print(f"{len(done)} Rmath exports")
