#!/usr/bin/env python3
"""Write src/stubs.rs: every function in tests/capi/symbols.tsv that
robigo-capi does not implement yet, exported as a stub that raises
"robigo: C API function 'X' is not implemented yet" (porting contract §6).
Package objects then load (their undefined symbols resolve) and fail with
an R error, not a crash, when they reach a missing function.

  crates/robigo-capi/gen-stubs.py          # rewrite src/stubs.rs
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TSV = os.path.join(ROOT, "tests", "capi", "symbols.tsv")


def census():
    out = []
    with open(TSV) as f:
        for line in f:
            if line.startswith("#") or line.startswith("symbol\t"):
                continue
            p = line.rstrip("\n").split("\t")
            out.append((p[0], p[1], int(p[2])))
    return out


def implemented():
    """Names exported by the hand-written modules (not stubs.rs)."""
    names = set()
    pat = re.compile(r'pub (?:unsafe )?(?:extern "C" fn|static mut) ([A-Za-z_][A-Za-z0-9_]*)')
    macro = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:=|,|\(|$)')
    src = os.path.join(HERE, "src")
    for fn in os.listdir(src):
        if not fn.endswith(".rs") or fn == "stubs.rs":
            continue
        text = open(os.path.join(src, fn)).read()
        names.update(pat.findall(text))
        # names generated by macros: sexp_globals!/sym_globals!/pred!/node_get!/...
        for m in re.finditer(r'(\w+)!\s*[\({]\s*\n?(.*?)\n[\)}]', text, re.S):
            if m.group(1) in ("sexp_globals", "sym_globals", "pred", "node_get", "setcxr"):
                for line in m.group(2).splitlines():
                    mm = macro.match(line)
                    if mm and mm.group(1)[0].isupper():
                        names.add(mm.group(1))
        for m in re.finditer(r'(?:typed_ptr|elt_accessors|get_region)!\(([^)]*)\)', text):
            parts = [p.strip() for p in m.group(1).split(",")]
            if m.group(0).startswith("typed_ptr"):
                names.update(parts[:3])
            elif m.group(0).startswith("elt_accessors"):
                names.update(parts[:2])
            else:
                names.add(parts[0])
    return names


def main():
    impl = implemented()
    rows = census()
    stubs = [(s, k) for s, k, _ in rows if s not in impl]
    with open(os.path.join(HERE, "src", "stubs.rs"), "w") as f:
        f.write("//! Generated by crates/robigo-capi/gen-stubs.py: the census symbols\n"
                "//! (tests/capi/symbols.tsv) robigo-capi does not implement yet. Calling\n"
                "//! one raises an R error that says so; data symbols are zero.\n\n"
                "#![allow(clippy::all)]\n\n"
                "use crate::errors::not_implemented;\n\n"
                "/// The stubbed function names (for the coverage report).\n"
                "pub static STUBS: &[&str] = &[\n")
        for s, k in stubs:
            if k == "function":
                f.write(f'    "{s}",\n')
        f.write("];\n\n")
        for s, k in stubs:
            if k == "function":
                f.write(f'#[unsafe(no_mangle)]\npub unsafe extern "C" fn {s}() {{\n    not_implemented("{s}")\n}}\n\n')
            else:
                f.write(f'#[unsafe(no_mangle)]\npub static mut {s}: [usize; 4] = [0; 4];\n\n')
    nf = sum(1 for _, k in stubs if k == "function")
    print(f"{len(rows) - len(stubs)} implemented, {nf} function stubs, {len(stubs) - nf} data stubs", file=sys.stderr)


if __name__ == "__main__":
    main()
