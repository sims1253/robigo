// The C shim: setjmp-based contexts and the register spill for the
// conservative stack scan (Rust cannot call setjmp); and robigo_layout.h,
// the object layout for C, written from the layout module's table.

// The layout's definitions, as a module of this script: constants only,
// over the SEXPTYPE numbers (src/layout/mod.rs).
#[allow(dead_code)]
#[path = "src/layout/defs.rs"]
mod layout;
#[allow(dead_code)]
#[path = "src/types.rs"]
mod types;

/// `robigo_layout.h`: one `#define ROBIGO_<name> <value>` per entry of
/// `layout::TABLE`, and the list of them as an X-macro, which C turns into
/// the table robigo-rtapi compares with the heap's at run time.
fn layout_header() -> String {
    let mut h = String::from(
        "/* robigo_layout.h: robigo's object layout for C (docs/g3.md §8).\n \
         * Generated by robigo-heap's build.rs from src/layout/defs.rs; do not\n \
         * edit. Offsets are bytes from an object's address (its SEXP); bit\n \
         * masks are of the header byte or word their prefix names. */\n\
         #ifndef ROBIGO_LAYOUT_H_\n#define ROBIGO_LAYOUT_H_\n\n",
    );
    for (name, v) in layout::TABLE {
        h += &format!("#define ROBIGO_{name} {v}\n");
    }
    h += &format!("\n#define ROBIGO_LAYOUT_COUNT {}\n", layout::TABLE.len());
    h += "#define ROBIGO_LAYOUT_TABLE(X) \\\n";
    for (name, _) in layout::TABLE {
        h += &format!("    X(ROBIGO_{name}) \\\n");
    }
    h += "\n\n#endif /* ROBIGO_LAYOUT_H_ */\n";
    h
}

// Recompiled when another checkout built last, not only rerun: this script
// compiles the layout's sources into itself (the modules above), and
// checkouts sharing a target directory share its compiled script, which
// cargo judges fresh by modification time. A checkout whose defs.rs is
// older than another checkout's build would run that build's script and
// write that checkout's header (A1's "layout table has another length 48
// vs 47"). Reading the variable here puts it in the script's own
// dependencies (rustc's dep-info), so another checkout's value recompiles
// it. (.cargo/config.toml sets ROBIGO_WORKTREE per checkout.)
const _: Option<&str> = option_env!("ROBIGO_WORKTREE");

/// The sources compiled into this script, as they were when it was
/// compiled, against the package's files now: a difference means cargo ran
/// a script compiled from another checkout's (or an older) layout, whose
/// header would be wrong. Read from the package's directory at run time
/// (CARGO_MANIFEST_DIR now: a compiled script outlives its checkout).
fn check_sources() {
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("robigo-heap: cargo sets CARGO_MANIFEST_DIR");
    for (path, compiled) in
        [("src/layout/defs.rs", include_str!("src/layout/defs.rs")), ("src/types.rs", include_str!("src/types.rs"))]
    {
        let file = std::path::Path::new(&dir).join(path);
        let now = std::fs::read_to_string(&file).unwrap_or_else(|e| panic!("robigo-heap: {}: {e}", file.display()));
        assert!(
            now == compiled,
            "robigo-heap: this build script was compiled from another {path} than {} (a build of another checkout \
             in the same target directory, reused by cargo): its robigo_layout.h would be wrong. Rebuild with \
             ROBIGO_WORKTREE set (the checkout's .cargo/config.toml, read when cargo runs inside the checkout), \
             or `touch crates/robigo-heap/build.rs`.",
            file.display()
        );
    }
}

fn main() {
    // Rerun when another checkout built last (.cargo/config.toml).
    println!("cargo:rerun-if-env-changed=ROBIGO_WORKTREE");
    println!("cargo:rerun-if-changed=src/types.rs");
    println!("cargo:rerun-if-changed=src/layout/defs.rs");
    check_sources();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let include = out.join("include");
    std::fs::create_dir_all(&include).expect("robigo-heap: creating OUT_DIR/include");
    let header = include.join("robigo_layout.h");
    let text = layout_header();
    // rewritten only when it changes, so that C depending on it is not
    // rebuilt for nothing
    if std::fs::read_to_string(&header).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&header, text).expect("robigo-heap: writing robigo_layout.h");
    }
    // the directory, for the build scripts of the crates that depend on
    // this one (`links`): DEP_ROBIGO_HEAP_INCLUDE
    println!("cargo:include={}", include.display());
    println!("cargo:rerun-if-changed=src/shim.c");
    println!("cargo:rerun-if-changed=src/test_routines.c");
    // No unwind tables, deliberately: Rust imports these functions as
    // `extern "C"` (no unwinding), so an exception must not get past them.
    // The unwinder's search phase stops at a frame without tables, so a C++
    // `throw` no `catch` below the shim handles ends in `std::terminate`
    // instead of finding a `catch` above Rust frames (docs/core.md §5).
    cc::Build::new()
        .file("src/shim.c")
        .flag_if_supported("-fno-omit-frame-pointer")
        .flag_if_supported("-fno-unwind-tables")
        .flag_if_supported("-fno-asynchronous-unwind-tables")
        .compile("robigo_heap_shim");
    // Package-routine stand-ins for tests/heap.rs, a separate archive
    // member: unreferenced, it stays out of every binary but the tests.
    cc::Build::new().file("src/test_routines.c").compile("robigo_heap_test_routines");
    // A package of its own for the pin report's tests: a shared library in
    // OUT_DIR, which they load with dlopen (Linux, where the report's tests
    // run).
    println!("cargo:rerun-if-changed=src/test_probe.c");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        let mut cmd = cc::Build::new().pic(true).get_compiler().to_command();
        cmd.args(["-shared", "-fPIC", "-o"]).arg(out.join("librobigo_heap_probe.so")).arg("src/test_probe.c");
        let ok = cmd.status().map(|s| s.success()).unwrap_or(false);
        assert!(ok, "robigo-heap: building the pin report's test library failed");
    }
}
