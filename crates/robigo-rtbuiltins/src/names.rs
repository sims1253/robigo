#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_reads() {
        assert!(INTERNALS.windows(2).all(|w| w[0].0.as_bytes() < w[1].0.as_bytes()));
        assert_eq!(internal_eval(b"mean"), Some(11));
        assert_eq!(internal_eval(b"vapply"), Some(10));
        assert_eq!(internal_eval(b"sum"), None);
        assert!(PRIMITIVES.windows(2).all(|w| w[0].0.as_bytes() < w[1].0.as_bytes()));
        assert_eq!(primitive_eval(b"~"), Some(0));
        assert_eq!(primitive_eval(b"sum"), Some(1));
        assert_eq!(primitive_eval(b"mean"), None);
    }
}
