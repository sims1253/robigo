## envir.c: .Internal(assign/get/get0/exists/mget) on environments, step by
## step (tests/envir.rs replays the same steps). Lines: TAG = value,
## TAG W : message, TAG E : message (hex).
show <- function(tag, expr) {
  res <- tryCatch(withCallingHandlers(list(v = expr), warning = function(w) {
    cat(tag, " W : ", .h(charToRaw(conditionMessage(w))), "\n", sep = "")
    invokeRestart("muffleWarning")
  }), error = function(e) {
    cat(tag, " E : ", .h(charToRaw(conditionMessage(e))), "\n", sep = "")
    NULL
  })
  if (!is.null(res)) cat(tag, " = ", enc(res$v), "\n", sep = "")
}
