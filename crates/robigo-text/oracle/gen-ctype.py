#!/usr/bin/env python3
"""Writes crates/robigo-text/src/tre/tables.rs.

    gen-ctype.py CTYPE > ../src/tre/tables.rs

CTYPE is ctype.R's output: glibc's C.UTF-8 iswctype classes and
towupper/towlower as GNU R 4.6.2 sees them. record.sh runs this.
"""
import sys

CLASSES = ["alnum", "alpha", "blank", "cntrl", "digit", "graph", "lower", "print",
           "punct", "space", "upper", "xdigit", "combining", "combining_level3"]


def main():
    classes = {k: [] for k in CLASSES}
    maps = {"upper": [], "lower": []}
    for line in open(sys.argv[1]):
        f = line.split()
        if not f:
            continue
        if f[0] == "class":
            classes[f[1]].append((int(f[2], 16), int(f[3], 16)))
        else:
            maps[f[0]].append((int(f[1], 16), int(f[2], 16)))
    # NUL cannot be in an R string; glibc's iswcntrl(0) is its only class.
    cntrl = classes["cntrl"]
    assert cntrl[0][0] == 1, "cntrl must start at U+0001"
    cntrl[0] = (0, cntrl[0][1])
    for t in list(classes.values()) + list(maps.values()):
        assert all(t[i][1] < t[i + 1][0] for i in range(len(t) - 1)) or \
            all(t[i][0] < t[i + 1][0] for i in range(len(t) - 1)), "unsorted table"
    print("// @generated by oracle/gen-ctype.py from GNU R 4.6.2; do not edit.")
    print()
    print("/// glibc's C.UTF-8 `iswctype` classes, in `Class` order: sorted")
    print("/// inclusive ranges of the code points in each class.")
    print("#[rustfmt::skip]")
    print(f"pub(super) static CLASSES: [&[(u32, u32)]; {len(CLASSES)}] = [")
    for k in CLASSES:
        r = classes[k]
        print(f"    // {k}")
        print("    &[")
        for i in range(0, len(r), 4):
            print("        " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in r[i:i + 4]))
        print("    ],")
    print("];")
    for name, key in (("TOUPPER", "upper"), ("TOLOWER", "lower")):
        r = maps[key]
        print()
        print(f"/// glibc's C.UTF-8 `tow{key}`: (code point, mapping) for every code")
        print("/// point it changes, sorted.")
        print("#[rustfmt::skip]")
        print(f"pub(super) static {name}: [(u32, u32); {len(r)}] = [")
        for i in range(0, len(r), 4):
            print("    " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in r[i:i + 4]))
        print("];")


main()
