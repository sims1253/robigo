#!/usr/bin/env python3
"""Writes crates/robigo-text/src/tables.rs.

    gen-tables.py ISWPRINT_RANGES RLOCALE_WIDTHS_H > ../src/tables.rs

ISWPRINT_RANGES is iswprint.R's output (glibc's C.UTF-8 iswprint as GNU R
4.6.2 sees it); RLOCALE_WIDTHS_H is R 4.6.2's src/main/rlocale_widths.h,
whose MB_Default column is the width table of every non-CJK locale.
record.sh runs this.
"""
import re
import sys


def ranges_rs(name, doc, ranges):
    out = [doc, "#[rustfmt::skip]", f"pub(crate) static {name}: [(u32, u32); {len(ranges)}] = ["]
    for i in range(0, len(ranges), 4):
        out.append("    " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in ranges[i:i + 4]))
    out.append("];")
    return "\n".join(out)


def unwin32(src):
    """The header as a non-Windows compiler sees it: `#ifdef Win32` blocks
    keep their `#else` branch."""
    out, state = [], None
    for line in src.split("\n"):
        d = line.split()
        if line.startswith("#ifdef") and d[1] == "Win32":
            state = "win"
        elif line.startswith("#else") and state == "win":
            state = "else"
        elif line.startswith("#endif") and state is not None:
            state = None
        elif line.startswith("#"):
            raise SystemExit(f"unexpected directive: {line}")
        elif state != "win":
            out.append(line)
    return "\n".join(out)


def main():
    isw = [tuple(int(v, 16) for v in line.split()) for line in open(sys.argv[1]) if line.strip()]
    src = unwin32(open(sys.argv[2]).read())
    body = src[src.index("table_wcwidth[] = {"):]
    body = body[:body.index("};")]
    widths = [(int(a, 16), int(b, 16), int(c.split(",")[0]))
              for a, b, c in re.findall(r"\{\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*,\s*\{([-0-9, ]+)\}\s*\}", body)]
    zb = src[src.index("zero_width[] = {"):]
    zb = zb[:zb.index("};")]
    zero = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\}", zb)]
    for t in (isw, [(a, b) for a, b, _ in widths], zero):
        assert all(t[i][1] < t[i + 1][0] for i in range(len(t) - 1)), "unsorted table"
    print("// @generated by oracle/gen-tables.py from GNU R 4.6.2; do not edit.")
    print()
    print(ranges_rs("ISWPRINT_C_UTF8",
                    "/// glibc's `iswprint` in C.UTF-8, as GNU R 4.6.2's EncodeString sees it:\n"
                    "/// sorted inclusive ranges of printable code points.", isw))
    print()
    print("/// R's `table_wcwidth` (rlocale_widths.h), column `MB_Default`: sorted")
    print("/// inclusive ranges and their width.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) static WCWIDTH: [(u32, u32, u8); {len(widths)}] = [")
    for i in range(0, len(widths), 3):
        print("    " + " ".join(f"(0x{a:x}, 0x{b:x}, {w})," for a, b, w in widths[i:i + 3]))
    print("];")
    print()
    print(ranges_rs("ZERO_WIDTH", "/// R's `zero_width` (rlocale_widths.h).", zero))


main()
