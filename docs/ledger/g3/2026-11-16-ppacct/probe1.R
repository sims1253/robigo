dyn.load(Sys.getenv("PPLEAK"))
mark <- function(s) cat("##", s, "\n", file = stderr())
mark("toplevel"); .Call("leak")
mark("invisible"); invisible(.Call("leak"))
mark("c1"); invisible(c(.Call("leak")))
mark("c2"); invisible(c(1, .Call("leak")))
mark("c3"); invisible(c(1, 2, .Call("leak")))
mark("plus"); invisible(1 + .Call("leak"))
mark("paren"); invisible((.Call("leak")))
mark("brace"); { .Call("leak") }
mark("if"); if (TRUE) .Call("leak")
mark("assign"); x <- .Call("leak")
mark("assign-brace"); x <- { .Call("leak") }
mark("print"); print(.Call("leak"))
f0 <- function() .Call("leak")
mark("closure1"); f0()
mark("closure2"); f0()
mark("closure3"); f0()
f1 <- function() { .Call("leak") }
mark("closure-brace"); f1()
f2 <- function(x) x
mark("promise"); f2(.Call("leak"))
f3 <- function(x) { x }
mark("promise-brace"); f3(.Call("leak"))
f4 <- function() { y <- .Call("leak"); y }
mark("closure-assign"); f4()
f5 <- function() return(.Call("leak"))
mark("return"); f5()
h <- function(n) if (n > 0) h(n - 1) else .Call("leak")
mark("h0"); h(0)
mark("h1"); h(1)
mark("h3"); h(3)
mark("for"); for (i in 1:2) .Call("leak")
mark("lapply"); invisible(lapply(1, function(i) .Call("leak")))
mark("local"); local(.Call("leak"))
mark("eval"); eval(quote(.Call("leak")))
mark("docall"); do.call(".Call", list("leak"))
g <- function(x) UseMethod("g"); g.default <- function(x) .Call("leak")
mark("usemethod"); g(1)
mark("trycatch"); tryCatch(.Call("leak"), error = function(e) NULL)
mark("end")
