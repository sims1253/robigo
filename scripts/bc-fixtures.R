# robigo-rt's byte-code translation cases (V3): GNU R 4.6.2's compiler
# (cmp.R's cmpfun) compiles each function below, and this script writes an
# R script that rebuilds every compiled closure from its code and
# constants (.Internal(mkCode()), .Internal(bcClose())) and calls it. Run
# by scripts/bc-fixtures.sh on the 4.6.2 oracle; the scripts it writes are
# tests/rt/bctrans/*.R, recorded on the oracle like any case: GNU R runs
# the rebuilt byte code, robigo-rt translates it.
#
#   Rscript --vanilla scripts/bc-fixtures.R CASES.R OUT.R
#
# CASES.R defines `cases`: a list of list(name, fun, calls), `fun` a
# function (compiled here), `calls` the R source of the calls to print; or
# list(name, expr, calls), `expr` top-level code (compiler::compile) the
# script binds to `name` as byte code.
args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) == 2L)
source(args[[1L]])
out <- args[[2L]]

dep <- function(x) paste(deparse(x, width.cutoff = 500L,
                               control = c("keepNA", "keepInteger", "niceNames", "showAttributes", "digits17")),
                       collapse = "\n")

# a disassembled code object: list(.Code, code, consts)
is_dis <- function(x) is.list(x) && length(x) == 3L && identical(x[[1L]], quote(.Code))

# R source that makes `x`, a constant of byte code
const <- function(x) {
  if (typeof(x) == "bytecode") return(code(.Internal(disassemble(x))))
  if (is_dis(x)) return(code(x))
  if (is.null(x)) return("NULL")
  if (is.symbol(x)) {
    if (identical(x, quote(expr = ))) return("quote(expr = )")
    return(sprintf("as.name(%s)", dep(as.character(x))))
  }
  if (is.language(x)) return(sprintf("quote(%s)", dep(x)))
  if (is.pairlist(x)) return(formals_src(x))
  if (is.list(x) && is.null(attributes(x))) {
    return(sprintf("list(%s)", paste(vapply(x, const, ""), collapse = ", ")))
  }
  if (is.environment(x) || is.function(x)) stop("a constant robigo cannot rebuild: ", typeof(x))
  dep(x)
}

# a pairlist of formals: as.pairlist(alist(...)), each default as written
formals_src <- function(f) {
  if (is.null(f)) return("NULL")
  n <- names(f)
  parts <- vapply(seq_along(f), function(i) {
    nm <- if (make.names(n[[i]]) == n[[i]] || n[[i]] == "...") n[[i]] else sprintf("`%s`", n[[i]])
    # (the missing argument cannot be bound to a variable)
    if (identical(f[[i]], quote(expr = ))) sprintf("%s = ", nm) else sprintf("%s = %s", nm, dep(f[[i]]))
  }, "")
  sprintf("as.pairlist(alist(%s))", paste(parts, collapse = ", "))
}

# R source that makes the code object `d` (disassembled)
code <- function(d) {
  sprintf("mk(%s, list(%s))", dep(as.integer(d[[2L]])),
          paste(vapply(d[[3L]], const, ""), collapse = ",\n  "))
}

lines <- c(
  "# Generated by scripts/bc-fixtures.R on GNU R 4.6.2 (do not edit): each",
  "# closure is GNU R's compiled code, rebuilt from its code and constants.",
  "mk <- function(code, consts) .Internal(mkCode(code, consts))",
  "")
for (cs in cases) {
  if (!is.null(cs$expr)) {
    # top-level code (compiler::compile), which eval() runs
    bc <- compiler::compile(cs$expr)
    lines <- c(lines, sprintf("# %s", cs$name),
               sprintf("%s <- %s", cs$name, code(.Internal(disassemble(bc)))), cs$calls, "")
    next
  }
  f <- compiler::cmpfun(cs$fun)
  bc <- .Internal(bodyCode(f))
  stopifnot(typeof(bc) == "bytecode")
  lines <- c(lines, sprintf("# %s", cs$name),
             sprintf("%s <- .Internal(bcClose(%s,\n %s,\n globalenv()))", cs$name,
                     formals_src(formals(f)), code(.Internal(disassemble(bc)))),
             cs$calls, "")
}
writeLines(lines, out)
