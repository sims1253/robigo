# Byte-code translation cases: complex assignments (STARTASSIGN to
# ENDASSIGN), each kind of getter and setter cmp.R compiles: `[<-`,
# `[[<-`, `$<-` and a call, nested, for the default method and an object's
# (scripts/bc-fixtures.R).
cases <- list(
  list(name = "k_sub", fun = function(x, i, v) { x[i] <- v; x },
       calls = c("print(k_sub(1:5, 2L, 10L))", "print(k_sub(c(a = 1, b = 2), 'b', 0))", "print(k_sub(NULL, 3, 'z'))")),
  list(name = "k_sub2", fun = function(l, n, v) { l[[n]] <- v; l },
       calls = c("print(k_sub2(list(1, 2), 2, 'two'))", "print(k_sub2(list(a = 1), 'b', TRUE))")),
  list(name = "k_dollar", fun = function(l, v) { l$a <- v; l },
       calls = c("print(k_dollar(list(b = 1), 2))", "print(k_dollar(list(a = 1), NULL))")),
  list(name = "k_call", fun = function(x) { names(x) <- c("p", "q"); x },
       calls = "print(k_call(1:2))"),
  list(name = "k_attr", fun = function(x) { attr(x, "foo") <- 1:2; attributes(x) },
       calls = "print(k_attr(3))"),
  list(name = "k_nested", fun = function(x) { names(x)[2] <- "z"; x },
       calls = "print(k_nested(c(a = 1, b = 2, c = 3)))"),
  list(name = "k_nested_dollar", fun = function(l) { l$a[2] <- 9; l$b$c <- "deep"; l },
       calls = "print(k_nested_dollar(list(a = 1:3, b = list(c = 0))))"),
  list(name = "k_nested_sub2", fun = function(l, i) { l[[i]]$b <- 1; l[[i]][["c"]] <- 2; l },
       calls = "print(k_nested_sub2(list(list(a = 0)), 1))"),
  list(name = "k_mat", fun = function(m) { m[1, 2] <- 0; m[[2, 3]] <- -1; m },
       calls = c("`[<-.mm` <- function(x, i, j, value) { attr(x, 'set') <- c(i, j, value); x }",
                 "`[[<-.mm` <- function(x, i, j, value) { attr(x, 'set2') <- c(i, j, value); x }",
                 "print(attributes(k_mat(structure(1, class = 'mm'))))")),
  list(name = "k_punt", fun = function(x) { x[] <- 0L; x },
       calls = "print(k_punt(1:3))"),
  list(name = "k_punt_getter", fun = function(x) { x[][2] <- 5L; x },
       calls = "print(k_punt_getter(1:3))"),
  list(name = "k_index_expr", fun = function(x, i) { x[i + 1] <- 0; x[[length(x)]] <- -1; x },
       calls = "print(k_index_expr(c(5, 6, 7, 8), 1))"),
  list(name = "k_index_if", fun = function(x, b) { x[if (b) 1 else 2] <- 0; x[c(if (b) 3, 4)] <- 9; x },
       calls = c("print(k_index_if(1:4, TRUE))", "print(k_index_if(1:4, FALSE))")),
  list(name = "k_super", fun = function() { v <- 1:3; f <- function() v[2] <<- 10L; f(); v },
       calls = "print(k_super())"),
  list(name = "k_value", fun = function(x) (x[1] <- 5),
       calls = c("print(k_value(1:2))", "k_value(1)")),
  list(name = "k_in_arg", fun = function(x) c(x[1] <- 2, x),
       calls = "print(k_in_arg(c(0, 1)))"),
  list(name = "k_method", fun = function(x) { x[3] <- "v"; x$m <- "w"; x },
       calls = c("`[<-.myc` <- function(x, i, value) structure(list(i = i, v = value), class = 'myc')",
                 "`$<-.myc` <- function(x, name, value) { y <- unclass(x); y[[name]] <- value; structure(y, class = 'myc') }",
                 "print(unclass(k_method(structure(list(), class = 'myc'))))")),
  list(name = "k_loop", fun = function(n) { x <- numeric(n); for (i in seq_len(n)) x[i] <- i^2; x },
       calls = "print(k_loop(4))"),
  list(name = "k_bad", fun = function(x) { x[[5]] <- NULL; x[[1]][[2]] <- 1; x },
       calls = "print(k_bad(list(1)))")
)
