# Byte-code translation cases: constants, variables, arithmetic,
# comparisons, logic, if, return, simple calls (scripts/bc-fixtures.R).
cases <- list(
  list(name = "k_const", fun = function() 42L, calls = "print(k_const())"),
  list(name = "k_null", fun = function() NULL, calls = "print(k_null())"),
  list(name = "k_arg", fun = function(x) x, calls = c("print(k_arg(3))", "print(k_arg('a'))")),
  list(name = "k_arith", fun = function(x, y) x + y * 2 - x / y,
       calls = c("print(k_arith(1, 2))", "print(k_arith(1:3, 2L))")),
  list(name = "k_unary", fun = function(x) -x + (+x), calls = "print(k_unary(5))"),
  list(name = "k_expt", fun = function(x) x^2 + sqrt(x), calls = "print(k_expt(4))"),
  list(name = "k_relop", fun = function(x, y) c(x < y, x <= y, x == y, x != y, x >= y, x > y),
       calls = "print(k_relop(1, 2))"),
  list(name = "k_logic", fun = function(x, y) c(x & y, x | y, !x), calls = "print(k_logic(TRUE, FALSE))"),
  list(name = "k_andor", fun = function(x, y) x && y || !x,
       calls = c("print(k_andor(TRUE, FALSE))", "print(k_andor(FALSE, stop('not reached')))")),
  list(name = "k_if", fun = function(x) if (x > 0) "pos" else if (x < 0) "neg" else "zero",
       calls = c("print(k_if(1))", "print(k_if(-1))", "print(k_if(0))")),
  list(name = "k_if_novalue", fun = function(x) { if (x) 1 }, calls = c("print(k_if_novalue(TRUE))", "print(k_if_novalue(FALSE))")),
  list(name = "k_assign", fun = function(x) { y <- x + 1; z <- y * 2; z },
       calls = "print(k_assign(1))"),
  list(name = "k_return", fun = function(x) { if (x) return("early"); "late" },
       calls = c("print(k_return(TRUE))", "print(k_return(FALSE))")),
  list(name = "k_invisible", fun = function(x) invisible(x), calls = c("k_invisible(1)", "print(k_invisible(2))")),
  list(name = "k_call", fun = function(x) paste("v", x, sep = "="), calls = "print(k_call(3))"),
  list(name = "k_closure_call", fun = function(f, x) f(x, 2), calls = "print(k_closure_call(function(a, b) a * b, 5))"),
  list(name = "k_missing", fun = function(x, y) missing(y), calls = c("print(k_missing(1))", "print(k_missing(1, 2))")),
  list(name = "k_default", fun = function(x, y = x * 2) x + y, calls = c("print(k_default(1))", "print(k_default(1, 5))")),
  list(name = "k_dots", fun = function(...) sum(...) + length(list(...)), calls = "print(k_dots(1, 2, 3))"),
  list(name = "k_superassign", fun = function() { n <- 0; f <- function() n <<- n + 1; f(); f(); n },
       calls = "print(k_superassign())")
)
