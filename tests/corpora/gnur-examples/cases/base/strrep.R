### Name: strrep
### Title: Repeat the Elements of a Character Vector
### Aliases: strrep
### Keywords: character

### ** Examples

strrep("ABC", 2)
strrep(c("A", "B", "C"), 1 : 3)
## Create vectors with the given numbers of spaces:
strrep(" ", 1 : 5)



