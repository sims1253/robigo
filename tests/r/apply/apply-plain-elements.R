# lapply/vapply over a plain vector or list read X[[i]] directly; FUN must
# see exactly what evaluating FUN(X[[i]], ...) gives it.
x <- c(a = 1.5, b = 2, c = NA)
print(lapply(x, function(v) v))
print(lapply(x, function(v) names(v)))
print(lapply(1:3, function(v) substitute(v)))
print(lapply(1:2, function(v) sys.call()))
print(lapply(1:2, function(v, ...) list(...), 10, k = "z"))
print(lapply(c(TRUE, NA), function(v, w) c(v, w), w = FALSE))
print(lapply(c("p", NA), nchar))
print(lapply(list(1:3, letters[1:2], NULL), length))
print(lapply(list(a = 1, b = list(2)), function(e) e))
print(lapply(1:3, `-`))
print(lapply(1:3, `-`, 1))
print(lapply(1:2, function(v, y) missing(y)))
print(vapply(c(u = 1, v = 4), sqrt, 0))
print(vapply(c("x", "yy"), nchar, 1L))
print(vapply(c("x", "yy"), nchar, 1L, USE.NAMES = FALSE))
print(vapply(list(1:2, 3:4), function(v) v * 2, numeric(2)))
print(vapply(list(1, "a"), is.character, NA))
print(vapply(1:3, function(i, n) i + n, 0, n = 0.5))
print(tryCatch(vapply(1:3, function(v) if (v == 2) 1:2 else 1L, 1L), error = conditionMessage))
print(tryCatch(vapply(1:2, function(v) "a", 1), error = conditionMessage))
e <- tryCatch(lapply(1:3, function(v) if (v == 3) stop("at three") else v), error = function(e) e)
print(conditionMessage(e)); print(conditionCall(e))
print(tryCatch(lapply(1:2, log, base = "a"), error = conditionMessage))
w <- withCallingHandlers(lapply(c(-1, 4), sqrt), warning = function(w) { print(conditionCall(w)); invokeRestart("muffleWarning") })
print(w)
# Objects take the general path (and their [[ methods).
f <- factor(c("lo", "hi", "lo"))
print(lapply(f, function(v) v))
print(vapply(f, as.character, ""))
print(lapply(data.frame(p = 1:2, q = c("a", "b")), class))
`[[.myl` <- function(x, i) paste("elt", i)
ml <- structure(list(1, 2), class = "myl")
print(lapply(ml, identity))
print(vapply(ml, nchar, 1L))
# A function that inspects its caller.
print(lapply(1:2, function(v) ls(parent.frame())))
print(lapply(1:2, function(v) get("i", parent.frame())))
print(sapply(list(a = 1:3, b = 4:6), mean))
print(Map(function(a, b) a + b, 1:2, 3:4))
print(lapply(integer(), identity))
print(vapply(character(), nchar, 1L))
