set.seed(42)
i <- 1:100; r <- 100:1; u <- sample(100)
cat(order(i), "\n")
cat(order(r), "\n")
cat(order(i, decreasing=TRUE), "\n")
cat(sort(i), "\n")
cat(sort(r, decreasing=TRUE), "\n")
cat(order(u), "\n")
cat(sort(u), "\n")
d <- sin(1:100)
cat(order(d), "\n")
cat(sort(d), "\n")
dr <- rev(sort(d))
cat(order(dr), "\n")
cat(order(dr, decreasing=TRUE), "\n")
t <- rep(1:10, each=10)
cat(order(t), "\n")
cat(sort(t), "\n")
og <- order(t, method="radix")
cat(attr(og, "ends"), "\n"); cat(attr(og, "maxgrpn"), "\n")
xn <- c(i, NA)
cat(order(xn), "\n")
cat(order(xn, na.last=FALSE), "\n")
cat(order(xn, na.last=NA), "\n")
cat(sort(xn, na.last=NA), "\n")
cat(sort(xn, decreasing=TRUE), "\n")
an <- c(NA, NA, NA)
cat(order(an, na.last=NA), "\n")
cat(order(an), "\n")
cat(order(an, decreasing=TRUE), "\n")
dn <- c(d, NA, NaN)
cat(order(dn), "\n")
cat(order(dn, na.last=FALSE), "\n")
cat(order(dn, na.last=NA), "\n")
cat(sort(dn, decreasing=TRUE, na.last=FALSE), "\n")
dd <- c(1, 1+1e-12, 2, 2+5e-13, 3)
od <- order(dd, method="radix")
cat(attr(od, "ends"), "\n"); cat(attr(od, "maxgrpn"), "\n")
m1 <- rep(1:10, each=20); m2 <- rep(1:10, each=20)
cat(order(m1, m2), "\n")
cat(order(m1, m2, decreasing=c(FALSE, TRUE)), "\n")
m3 <- rep(rev(1:10), each=20)
cat(order(m1, m3), "\n")
cat(rank(u), "\n")
cat(sort.list(i), "\n")
f <- factor(sample(letters[1:5], 100, replace=TRUE))
cat(order(f), "\n")
cat(sort(f), "\n")
og2 <- order(c(2,2,3,3,3,1), method="radix")
cat(og2, "\n"); cat(attr(og2, "ends"), "\n"); cat(attr(og2, "maxgrpn"), "\n")
l <- rep(c(TRUE, FALSE, NA), 5)
cat(order(l), "\n")
cat(sort(l), "\n")
cat(order(l, na.last=FALSE), "\n")
# near-sorted (one inversion)
ns <- i; ns[50] <- 99L; ns[99] <- 50L
cat(order(ns), "\n")
# reversed with ties -> NOT strictly reversed
rt <- c(5,4,3,3,2,1)
cat(order(rt), "\n")
cat("done\n")
