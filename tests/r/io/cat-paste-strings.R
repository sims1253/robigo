# cat() and paste(collapse=) of character vectors: separators, NA, filling,
# labels, numbers among strings, recycling, encodings.
s <- c("a", "c", NA, "t", "", "é")
cat(s, "\n", sep = "")
cat(s, "\n")
cat(s, sep = c("-", "+", "\n"))
cat("\n")
cat(s, 1.5, 2L, TRUE, NA, s, "\n", sep = "|")
cat("x", character(), "y", NULL, "z\n")
cat(s, fill = 10)
cat(s, fill = 8, labels = c("L1:", "L2:"))
cat(s, "end", sep = "\n")
cat(paste(s, collapse = ""), "\n", sep = "")
print(paste(s, collapse = ""))
print(paste(s, collapse = "+"))
print(paste(s, 1:2, sep = "_", collapse = "|"))
print(paste0(s, collapse = NULL))
print(paste(s, collapse = NULL))
print(paste(character(), collapse = "x"))
print(paste("a", character(), collapse = "x"))
print(paste(c("a", NA), c("b", "c", "d"), sep = "", collapse = ""))
print(paste(list("a", 1, TRUE, NULL), collapse = "/"))
print(Encoding(paste(c("a", "é"), collapse = "")))
print(nchar(paste(rep("acgt", 15), collapse = "")))
f <- function(n) for (i in 1:n) cat(paste(rep(c("g", "c"), 30), collapse = ""), "\n", sep = "")
f(3)
