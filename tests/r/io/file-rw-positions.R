# File connections keep separate read and write positions (connections.c
# fileconn rpos/wpos): parse_Rd writes lines to file() and reads them back.
tcon <- file()
writeLines(c("first", "second"), tcon)
readLines(tcon)
writeLines("third", tcon)
readLines(tcon)
close(tcon)
f <- tempfile()
con <- file(f, "w+")
cat("abc\ndef\n", file = con)
readLines(con, n = 1)
cat("ghi\n", file = con)
readLines(con)
seek(con, rw = "read")
seek(con, rw = "write")
seek(con, 0, rw = "read")
readLines(con)
close(con)
readLines(f)
unlink(f)
