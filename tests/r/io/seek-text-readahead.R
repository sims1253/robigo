# seek() on a text-mode reading file connection returns the OS file
# position, which includes R's 4096-byte read-ahead buffer (connections.c
# buff_seek -> file_seek returns f_tell(fp)), and a tell (where = NA)
# subtracts the unread part of that buffer.
tmp <- tempfile()
cat(c("1\t2\t3", "4\t5\t6"), file = tmp, sep = "\n")
fd <- file(tmp, open = "rt")
scan(file = fd, what = double(), n = 2)
seek(fd)
seek(con = fd, where = 0, origin = "start")
z <- scan(file = fd, what = double(), n = 2)
z
seek(fd)
close(fd)
unlink(tmp)
f <- tempfile()
writeLines(c("abc","defgh","ij"), f)
con <- file(f, "r")
readLines(con, 1)
seek(con)
readLines(con, 1)
seek(con)
seek(con, 0)
readLines(con, 1)
seek(con, 1, origin="current")
readLines(con)
close(con)
con <- file(f, "rb"); readLines(con,1); seek(con); close(con)
con <- file(f); open(con, "r"); readChar(con, 2); seek(con); close(con)
con <- file(f, "r"); pushBack("zz", con); seek(con); readLines(con,1); seek(con); close(con)
con <- file(f, "r"); scan(con, what="", n=1); seek(con); close(con)
con <- file(f, "r+"); readLines(con,1); seek(con); seek(con, rw="write"); close(con)
con <- file(f, "r", encoding="latin1"); readLines(con,1); seek(con); close(con)
con <- file(f, "r")
readLines(con, 1); seek(con)
x <- readLines(con, 400); seek(con)
seek(con, 5, origin = "current"); readLines(con, 1); seek(con)
seek(con, 5000, origin = "current"); readLines(con, 1); seek(con)
seek(con, -20, origin = "end"); readLines(con); seek(con)
seek(con, 0); readLines(con, 1)
close(con)
con <- file(f, "r+")
readLines(con, 2); seek(con); seek(con, rw = "write")
writeLines("XXXX", con); seek(con); seek(con, rw = "read")
readLines(con, 1); seek(con)
close(con)
readLines(f, 4)
writeLines(c("x <- 1; y <- 2", "z <- 3", "w"), f)
con <- file(f, "r"); parse(con, n = 1); seek(con); readLines(con); close(con)
con <- file(f, "r"); parse(con, n = 1); seek(con, 1, origin = "current"); readLines(con); close(con)
con <- file(f, "r"); scan(con, what = "", n = 2, quiet = TRUE); seek(con); close(con)
con <- file(f, "rb"); readLines(con, 1); seek(con); seek(con, 2, origin="current"); readLines(con, 1); close(con)
# a negative relative seek steps back within R's buffer (the file stays put)
writeLines(c("abc", "defgh", "ij"), f)
con <- file(f, "r")
readLines(con, 1); seek(con, -1, origin = "current"); seek(con, 0); readLines(con)
close(con)
con <- file(f, "r")
readLines(con, 1); seek(con, -3, origin = "current"); readLines(con, 1); seek(con)
close(con)
# reading what R buffered keeps a read-write connection writing
con <- file(f, "r+")
readLines(con, 1); writeLines("X", con); readLines(con, 1); seek(con)
seek(con, rw = "write"); readLines(con); seek(con)
close(con)
readLines(f)
con <- file(f, "r+")
readLines(con, 1); writeLines("X", con); scan(con, what = "", n = 1, quiet = TRUE); seek(con)
close(con)
# skipping exactly what the parser left unread
writeLines(c("1 + ) abc", "defgh", "ij"), f)
con <- file(f, "r"); try(parse(con, n = 1)); seek(con, 5, origin = "current"); readLines(con); close(con)
con <- file(f, "r"); try(parse(con, n = 1)); seek(con, 4, origin = "current"); readLines(con); close(con)
con <- file(f, "r"); try(parse(con, n = 1)); seek(con, -2, origin = "current"); readLines(con, 1); close(con)
# a step back past what the parser left unread stays within R's buffer too
con <- file(f, "r"); try(parse(con, n = 1)); seek(con, -2, origin = "current"); seek(con, 0); readLines(con); close(con)
con <- file(f, "r"); try(parse(con, n = 1)); seek(con); seek(con, -4, origin = "current"); seek(con); readLines(con, 1); close(con)
# ... back into bytes read before the parse began
writeLines(c("x <- 1", "1 + ) abc", "defgh", "ij"), f)
con <- file(f, "r"); parse(con, n = 1); try(parse(con, n = 1)); seek(con); seek(con, -9, origin = "current"); seek(con); readLines(con, 2); close(con)
# ... counting the CRs that were read as LF
writeBin(charToRaw("x <- 1\r\n1 + ) abc\r\ndefgh\r\nij\r\n"), f)
con <- file(f, "r"); parse(con, n = 1); try(parse(con, n = 1)); seek(con); seek(con, -3, origin = "current"); seek(con); readLines(con, 2); close(con)
writeBin(charToRaw("x <- 1\r1 + ) a\rbc\rdefgh\r"), f)
con <- file(f, "r"); parse(con, n = 1); try(parse(con, n = 1)); seek(con); seek(con, -3, origin = "current"); seek(con); readLines(con); close(con)
unlink(f)
