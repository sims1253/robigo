# Socket connections on the loopback interface. The port is fixed, not 0:
# nothing in R reports which one a server socket got.
port <- 25631L
srv <- serverSocket(port)
print(class(srv))
s <- summary(srv)
print(s$class); print(s$description); print(s$mode); print(s$opened)
print(isOpen(srv))

c1 <- socketConnection("localhost", port, open = "a+b", blocking = TRUE, timeout = 5)
s1 <- socketAccept(srv, blocking = TRUE, open = "a+b", timeout = 5)
print(class(c1))
print(summary(c1)$description)
print(summary(s1)$description)
print(summary(s1)$text)
print(socketSelect(list(srv), FALSE, 0))
print(socketSelect(list(s1), FALSE, 0))
print(socketSelect(list(s1), TRUE, 0))

# objects, one at a time: what follows on the stream stays there
serialize(list(a = 1:3, b = "x", f = function(x) x + 1), c1)
print(socketSelect(list(s1, c1), c(FALSE, FALSE), 2))
r <- unserialize(s1)
print(r$a); print(r$f(1))
serialize("one", c1)
serialize("two", c1)
print(unserialize(s1))
print(unserialize(s1))
serialize(seq_len(100000), s1)
print(length(unserialize(c1)))
serialize(as.list(1:5000), s1)
print(length(unserialize(c1)))

# what a read buffered counts as readable
writeBin(as.raw(1:6), c1)
print(readBin(s1, "raw", 2))
print(socketSelect(list(s1), FALSE, 0))
print(readBin(s1, "raw", 4))

# text on a binary socket
writeBin(charToRaw("line one\nline two\n"), c1)
print(readLines(s1, 2))

# timeouts
print(socketTimeout(s1, 1L))
print(socketTimeout(s1))
print(socketTimeout(s1, -1L))
print(socketTimeout(s1))
print(readBin(s1, "raw", 1))
close(c1); close(s1)

# the peer has gone
c2 <- socketConnection("localhost", port, open = "r+b", blocking = TRUE, timeout = 5)
s2 <- socketAccept(srv, blocking = TRUE, open = "r+b", timeout = 5)
close(c2)
print(readBin(s2, "raw", 1))
print(tryCatch(unserialize(s2), error = conditionMessage))
close(s2)

# a text socket, and not blocking
c3 <- socketConnection("localhost", port, open = "a+", blocking = FALSE, timeout = 5)
s3 <- socketAccept(srv, blocking = FALSE, open = "a+", timeout = 5)
print(summary(s3)$text)
print(readLines(s3))
print(isIncomplete(s3))
writeLines(c("a", "b"), c3)
print(socketSelect(list(s3), FALSE, 2))
print(readLines(s3))
close(c3); close(s3)

# created closed: each implicit open accepts again from the server socket
c5 <- socketConnection("localhost", port, open = "a+", blocking = TRUE, timeout = 5)
c6 <- socketConnection("localhost", port, open = "a+", blocking = TRUE, timeout = 5)
s5 <- socketAccept(srv, open = "", blocking = TRUE, timeout = 5)
print(isOpen(s5))
writeLines("first", c5)
print(readLines(s5, 1))
print(isOpen(s5))
writeLines("second", c6)
print(readLines(s5, 1))
close(c5); close(c6); close(s5)

# an open connection does not keep the server socket's port
srv3 <- serverSocket(25634L)
c7 <- socketConnection("localhost", 25634L, open = "a+b", blocking = TRUE, timeout = 5)
s7 <- socketAccept(srv3, open = "a+b", blocking = TRUE, timeout = 5)
close(srv3)
srv4 <- serverSocket(25634L)
print(class(srv4)[1])
close(srv4)
close(c7); close(s7)
srv5 <- serverSocket(25634L)
c8 <- socketConnection("localhost", 25634L, open = "a+b", blocking = TRUE, timeout = 5)
s8 <- socketAccept(srv5, open = "", blocking = TRUE, timeout = 5)
open(s8, "a+b")
close(srv5)
srv6 <- serverSocket(25634L)
print(class(srv6)[1])
close(srv6)
close(c8); close(s8)

# opened later
c4 <- socketConnection("localhost", port, open = "", blocking = TRUE, timeout = 5)
print(isOpen(c4))
print(summary(c4)$description)
open(c4, "a+b")
print(summary(c4)$description)
s4 <- socketAccept(srv, blocking = TRUE, open = "a+b", timeout = 5)
close(c4); close(s4)
close(srv)

# errors
