print(tryCatch(socketAccept(stdin()), error = conditionMessage))
print(tryCatch(serverSocket(NA), error = conditionMessage))
print(tryCatch(serverSocket(-1L), error = conditionMessage))
print(tryCatch(socketSelect(1L), error = conditionMessage))
print(tryCatch(socketSelect(list()), error = conditionMessage))
print(tryCatch(socketSelect(list(stdin())), error = conditionMessage))
print(tryCatch(socketSelect(list(stdin()), 1L), error = conditionMessage))
print(tryCatch(socketTimeout(stdin()), error = conditionMessage))
print(tryCatch(socketConnection(1, 1L), error = conditionMessage))
print(tryCatch(socketConnection("localhost", -1L), error = conditionMessage))
print(tryCatch(socketConnection("localhost", 25632L, open = "r", blocking = TRUE, timeout = 1), warning = conditionMessage))
