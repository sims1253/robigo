show_error <- function(expr) tryCatch(expr, error = function(e) cat(conditionMessage(e), "\n", sep = ""))
show_error(tracemem(NULL))
show_error(tracemem(function() NULL))
show_error(tracemem(baseenv()))
show_error(tracemem(y = NULL))
show_error(untracemem(function() NULL))
show_error(untracemem(y = NULL))
show_error(retracemem(1:3, 1:2))
show_error(retracemem(1:3, c("a", "b")))
show_error(retracemem(function() NULL, 1:2))
show_error(retracemem(1:3, extra = TRUE))
withVisible(retracemem(NULL))
withVisible(untracemem(NULL))
