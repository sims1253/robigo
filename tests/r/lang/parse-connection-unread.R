# parse(con, n =) reads a connection on demand (R: gram.c:con_getc), so
# what its lexer has not read is still there for the next reader: after a
# statement's terminator, or where an error was raised. The lexer reads one
# character past a symbol, a number or an operator that could go on, and
# the whole of a character an invalid byte announces (mbcs_get_next).
tf <- tempfile()
b <- function(...) unlist(lapply(list(...), function(x) if (is.character(x)) charToRaw(x) else as.raw(x)))
try1 <- function(expr) tryCatch(expr, error = function(e) paste("Error:", conditionMessage(e)))
probe <- function(bytes, n = 1) {
  writeBin(bytes, tf)
  con <- file(tf, "r")
  on.exit(close(con))
  print(try1(parse(con, n = n)))
  print(readLines(con))
}
# 0xFF announces six bytes: they run past the first newline
probe(b(0xFF, 0x0A, "123456\n7\n"))
probe(b(0xFF, "123456789\n7\n"))
probe(b("x\n", 0xFF, "123456789\n7\n"), n = 2)
probe(b(0xE7, "\n7\n"))
probe(b("x <- ", 0xF0, "\n9\n"))
probe(b("x", 0xFF, "y\nnext\n"))
probe(b("'abc", 0xFF, "' def\nnext\n"))
probe(b("x <- 'a\\q'\nnext\n"))
# a comment's invalid bytes are never decoded
probe(b("x # ", 0xFF, "\nnext\n"))
# syntax errors: the token after the one in error, and the character after it
probe(b("x y z\nfoo\n"))
probe(b("x <- 1 2 3\nfoo\n"))
probe(b("x <- 10L5\nnext\n"))
probe(b("x <- 0x\nnext\n"))
probe(b("x <- 1 )\nnext\n"))
probe(b("f <- function() {\n  x +\n}\nnext\n"))
probe(b("x <- 1; y <- ;\nnext\n"), n = 2)
probe(b("x = 1 ; ; y\nq\n"), n = 2)
probe(b("x[[1]\nnext\n"))
# statements end at their terminator
probe(b("a; b\nc\n"))
probe(b("if (TRUE) 1\nelse 2\nz\n"))
probe(b("x <- (1 +\n2)\nnext\n"))
probe(b("x <- 1\r\ny\r\nz\r\n"))

# The bytes left over are in the connection, not pushed back
writeBin(b(0xFF, "123456789\n7\n"), tf)
con <- file(tf, "r")
print(try1(parse(con, n = 1)))
print(pushBackLength(con))
clearPushBack(con)
print(readLines(con, n = 1))
close(con)
con <- file(tf, "r")
print(try1(parse(con, n = 1)))
print(seek(con))
pushBack("pb", con)
print(readLines(con))
close(con)

# another parse, scan, a text connection, a compressed file, an encoding
writeBin(b("x y\nz <- 1\nw\n"), tf)
con <- file(tf, "r")
print(try1(parse(con, n = 1)))
print(parse(con, n = 1))
print(readLines(con))
close(con)
writeBin(b("x 1 2 3\n4\n"), tf)
con <- file(tf, "r")
print(try1(parse(con, n = 1)))
print(scan(con, quiet = TRUE))
close(con)
tc <- textConnection(c("a b c", "d"))
print(try1(parse(tc, n = 1)))
print(readLines(tc))
close(tc)
gz <- tempfile(fileext = ".gz")
g <- gzfile(gz, "w"); writeLines(c("1 2 3", "nx"), g); close(g)
g <- gzfile(gz, "r")
print(try1(parse(g, n = 1)))
print(readLines(g))
close(g)
writeBin(b("x <- 1 2 3\nfoo\n"), tf)
con <- file(tf, "r", encoding = "latin1")
print(try1(parse(con, n = 1)))
print(readLines(con))
close(con)
unlink(c(tf, gz))
