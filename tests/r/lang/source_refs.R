options(keep.parse.data = FALSE)
show_ref <- function(x) print(as.integer(x))
show_attrs <- function(x) {
    print(names(attributes(x)))
    for (s in attr(x, 'srcref')) show_ref(s)
    show_ref(attr(x, 'wholeSrcref'))
    invisible(NULL)
}
p <- parse(text = '1+1;bar()', keep.source = TRUE)
show_attrs(p)
print(attributes(p[1]))
print(identical(attr(p, 'srcfile'), attr(attr(p, 'srcref')[[1]], 'srcfile')))
show_attrs(parse(text = '# comment\n\té + 1', keep.source = TRUE))
p <- parse(text = '{ x; { y }; function(a = function() 1) { a } }', keep.source = TRUE)
show_attrs(p[[1]])
show_attrs(p[[1]][[3]])
f <- p[[1]][[4]]
show_ref(f[[4]])
show_ref(f[[2]][[1]][[4]])
show_attrs(f[[3]])
show_attrs(parse(text = '1; 2\n3', n = 1, keep.source = TRUE))
show_attrs(parse(text = '1; 2\n3', n = 2, keep.source = TRUE))
show_attrs(parse(text = '# comment only', keep.source = TRUE))
print(attributes(parse(text = '1+1', keep.source = FALSE)))
