# Bessel functions (base), negative binomial and hypergeometric (.Internal)
op <- function(x) print(x, digits = 15)
op(besselJ(c(0, 0.5, 1, 2.5, 10, 100, 1e5), 0))
op(besselJ(c(1, 10, 1e5), c(0.5, 2.5, -1.5)))
op(besselY(c(0.1, 1, 10, 1e4), 1.5))
op(besselY(2, c(-2.5, 0, 3, 30)))
op(besselI(c(0, 0.1, 1, 10, 100), 1))
op(besselI(c(1, 10, 700), 2.5, TRUE))
op(besselI(5, c(-1.5, 0, 0.5, 40)))
op(besselK(c(1e-5, 0.1, 1, 10, 500), 0))
op(besselK(c(1e-5, 2, 800), 30, TRUE))
op(besselK(3, c(-2.5, 0.5, 7)))
besselJ(-1, 0.5)
besselI(c(a = 1, b = 2), 0)
op(.Internal(dnbinom(0:6, 3, 0.4, FALSE)))
op(.Internal(dnbinom(c(5, 1e4), c(0.5, 1e3), 0.1, TRUE)))
op(.Internal(pnbinom(c(0, 2, 10, 100), 3, 0.4, TRUE, FALSE)))
op(.Internal(pnbinom(c(2, 50), 3, 0.4, FALSE, TRUE)))
op(.Internal(qnbinom(c(0, 0.1, 0.5, 0.99, 1), 3, 0.4, TRUE, FALSE)))
op(.Internal(dnbinom_mu(0:5, 2.5, 4, FALSE)))
op(.Internal(pnbinom_mu(c(1, 4, 20), 2.5, 4, TRUE, FALSE)))
op(.Internal(qnbinom_mu(c(0.05, 0.5, 0.95), 2.5, 4, TRUE, FALSE)))
op(.Internal(dhyper(0:4, 5, 7, 4, FALSE)))
op(.Internal(dhyper(c(10, 200), 300, 700, 400, TRUE)))
op(.Internal(phyper(0:4, 5, 7, 4, TRUE, FALSE)))
op(.Internal(phyper(c(100, 150), 300, 700, 400, FALSE, TRUE)))
op(.Internal(qhyper(c(0, 0.2, 0.5, 0.9, 1), 5, 7, 4, TRUE, FALSE)))
.Internal(dhyper(1.5, 5, 7, 4, FALSE))
set.seed(1)
.Internal(rhyper(10, 5, 7, 4))
.Internal(rhyper(5, 300, 700, 400))
.Internal(rhyper(3, c(1e5, 10), 2e5, 5e4))
.Internal(runif(2, 0, 1))
