# Complex vector arithmetic: recycling, special values, attributes.
z <- complex(real = c(1, -2, 0, Inf, NaN, 3), imaginary = c(2, 0.5, -1, 1, 0, -Inf))
w <- c(1+1i, 2-3i)
print(z * w)
print(z / w)
print(z + w)
print(z - w)
print(z ^ 2)
print(w ^ z[1:2])
print(z * 2)
print(2 / z)
print(1:6 * z)
print(z * c(TRUE, FALSE, NA))
print(complex(0) * z)
print(z[0] + 1i)
# overflow to Inf and NaN, as in an escaping Mandelbrot iteration
c0 <- complex(real = c(-2, 0.3, 1.5), imaginary = c(1, 0.5, 1))
zz <- complex(3)
for (i in 1:12) zz <- zz * zz + c0
print(zz)
print(zz * zz)
print(c(Inf+0i, NaN+0i, NA) * c(0+1i, Inf+Inf*1i, 1+0i))
print(complex(real = Inf, imaginary = NaN) * complex(real = 0, imaginary = 2))
print(complex(real = NaN, imaginary = Inf) * complex(real = 2, imaginary = 0))
print(c(1+1i, 0+0i) / c(0+0i, 0+0i))
m <- matrix(z, 2, dimnames = list(c("r1", "r2"), NULL))
print(m * w)
print(m / 1i)
names(w) <- c("p", "q")
print(w * 1i)
print(tryCatch(z %% w, error = conditionMessage))
print(complex(0) %% 1i)
print(z * w[1:2] * 1:4)
