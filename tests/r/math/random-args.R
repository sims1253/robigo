.Internal(runif(1, 0, 1))
.Internal(sample(1e6, 3, TRUE, NULL))
.Internal(runif(3, -Inf, 1))
.Internal(runif(2, 1, 0))
.Internal(rnorm(2, 0, -1))
.Internal(rbinom(4, c(10, NA), 0.5))
.Internal(rpois(2, numeric(0)))
.Internal(runif(c(5, 6, 7), 0, 1))
.Internal(runif(list(1, 2), 0, 1))
.Internal(runif("3", 0, 1))
.Internal(runif(2, "a", 1))
