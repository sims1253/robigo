print(.Internal(rchisq(5, 3)), digits = 15)
print(.Internal(rt(5, 4)), digits = 15)
print(.Internal(rf(5, 3, 7)), digits = 15)
print(.Internal(rcauchy(5, 0, 1)), digits = 15)
print(.Internal(rlnorm(5, 0, 1)), digits = 15)
print(.Internal(rlogis(5, 0, 1)), digits = 15)
print(.Internal(rweibull(5, 2, 1)), digits = 15)
.Internal(rgeom(10, 0.3))
.Internal(rnbinom(10, 3, 0.5))
.Internal(rnbinom_mu(5, 2, 4))
