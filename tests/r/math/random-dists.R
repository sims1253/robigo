# Random variate generators from nmath, via their .Internal()s
set.seed(1)
.Internal(rbinom(10, 10, 0.3))
.Internal(rbinom(5, 1000, 0.4))
.Internal(rbinom(5, 100, 0.9))
.Internal(rbinom(3, 0, 0.5))
.Internal(rpois(10, 3))
.Internal(rpois(5, 100))
.Internal(rpois(5, 15.5))
.Internal(rpois(3, c(0, 1, 1e6)))
print(.Internal(rexp(5, 1)), digits = 15)
print(.Internal(rexp(3, 0.5)), digits = 15)
print(.Internal(rgamma(5, 0.5, 1)), digits = 15)
print(.Internal(rgamma(5, 2.5, 2)), digits = 15)
print(.Internal(rgamma(5, 20, 1)), digits = 15)
print(.Internal(rbeta(5, 0.5, 0.7)), digits = 15)
