# Mersenne-Twister streams after set.seed(); runif/rnorm are stats-only,
# their .Internal()s are in base.
set.seed(42)
.Internal(runif(5, 0, 1))
.Internal(rnorm(5, 0, 1))
.Internal(sample(10, 10, FALSE, NULL))
set.seed(42)
print(.Internal(runif(3, 0, 1)), digits = 17)
print(.Internal(rnorm(3, 10, 2)), digits = 17)
set.seed(1)
.Random.seed
set.seed(123)
.Internal(runif(4, c(0, 10), c(1, 20)))
.Internal(rnorm(4, c(0, 100), 1))
.Internal(runif(0, 0, 1))
.Internal(rnorm(2, 0, 0))
.Internal(runif(2, 3, 3))
set.seed(2024)
x <- .Internal(runif(1000, 0, 1))
.Internal(runif(2, 0, 1))
# generator state survives across calls
