# gctorture() returns whether torture was on; gctorture2() the old step.
# Steps are large so that GNU R does not collect on every allocation.
print(gctorture(FALSE))
print(gctorture2(1000))
print(gctorture(FALSE))
print(gctorture(FALSE))
x <- gctorture2(1000); y <- gctorture2(0)
print(c(x, y))
gctorture()
print(gctorture(FALSE))
print(gctorture2(500, 1000))
print(gctorture2(700, inhibit_release = TRUE))
# negative and NA steps change nothing, a wait without a step neither
print(gctorture2(-1))
print(gctorture2(NA))
print(gctorture2(NA, 5))
print(gctorture2(0, 5))
print(gctorture2(0))
# non-logical 'on' is a step (asInteger: the first element, with warnings)
print(gctorture(600.9))
print(gctorture2(0))
print(gctorture("800"))
print(gctorture(0))
print(gctorture2(c(900, 1), c(2000, 1)))
print(gctorture(list(1)))
print(gctorture2(0))
print(gctorture(-5))
print(gctorture(FALSE))
r <- withCallingHandlers(gctorture("a"), warning = function(w) {
    print(conditionMessage(w)); invokeRestart("muffleWarning")
})
print(r)
r <- withCallingHandlers(gctorture2(1000, "b"), warning = function(w) {
    print(conditionMessage(w)); invokeRestart("muffleWarning")
})
print(r)
print(gctorture2(0))
print(gctorture(FALSE))
# errors
f <- function(expr) tryCatch(expr, error = function(e) print(conditionMessage(e)))
f(gctorture(NA))
f(gctorture(logical()))
f(gctorture(c(TRUE, FALSE)))
f(gctorture2(1000, inhibit_release = NA))
f(gctorture2(1000, inhibit_release = "maybe"))
f(gctorture2(1000, inhibit_release = c(TRUE, FALSE)))
f(gctorture2(1000, inhibit_release = list()))
print(gctorture2(0))
f(gctorture2())
print(gctorture2(0))
f(.Internal(gctorture()))
f(.Internal(gctorture2(1, 2)))
print(gctorture(FALSE))
print(withVisible(gctorture(FALSE))$visible)
print(withVisible(gctorture2(0))$visible)
