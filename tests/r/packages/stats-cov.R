library(stats)
x <- c(2.1, 3.4, 1.9, 5.6, 4.4, 3.3)
y <- c(1.0, 2.5, 0.7, 4.9, 3.1, 2.2)
var(x)
sd(x)
cov(x, y)
cor(x, y)
cor(x, y, method = "kendall")
cor(x, y, method = "spearman")
m <- cbind(a = x, b = y, c = x * y - 3)
var(m)
cor(m)
cov(m, method = "kendall")
xn <- c(1, NA, 3, 4, 5)
var(xn)
var(xn, na.rm = TRUE)
cor(cbind(xn, 1:5), use = "pairwise.complete.obs")
cor(cbind(xn, 1:5), use = "complete.obs")
cor(cbind(xn, 1:5))
var(c(1e10 + 1, 1e10 + 2, 1e10 + 3))
sd(1:10 / 7)
cor(1:10, rep(1, 10))
tryCatch(var(factor(1:3)), error = function(e) conditionMessage(e))
tryCatch(var(numeric(0)), error = function(e) conditionMessage(e))
tryCatch(cor(1:3, 1:4), error = function(e) conditionMessage(e))
var(c(1, NA, 3), use = "everything")
var(1)
set.seed(7)
z <- matrix(rnorm(60), 20)
sprintf("%.17g", c(var(x), sd(x), cov(x, y), cor(x, y), var(z), cor(z), cor(z, method = "kendall")))
sprintf("%.17g", c(var(c(0.1, 0.2, 0.3)), sd(c(1e-300, 2e-300, 3e-300)), var(1:1000 / 3)))
