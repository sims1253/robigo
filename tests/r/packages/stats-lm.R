library(stats)
x <- c(1, 2, 3, 4, 5, 6, 7, 8)
y <- c(1.2, 1.9, 3.2, 3.8, 5.1, 6.3, 6.8, 8.1)
fit <- lm(y ~ x)
fit
coef(fit)
sprintf("%.17g", coef(fit))
residuals(fit)
fitted(fit)
summary(fit)
anova(fit)
g <- gl(2, 4)
summary(lm(y ~ x * g))
predict(fit, data.frame(x = c(9, 10)))
predict(fit, data.frame(x = 9), interval = "confidence")
confint(fit)
qr(cbind(1, x))$rank
qr.solve(cbind(1, x), y)
X <- cbind(1, x, x^2)
round(qr.Q(qr(X)), 6)
round(qr.R(qr(X)), 6)
lm(y ~ x - 1)
lm(y ~ poly(x, 2))
