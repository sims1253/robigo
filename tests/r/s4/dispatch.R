# setGeneric, setMethod, inheritance, callNextMethod, missing, primitives
library(methods)
setGeneric("area", function(shape, ...) standardGeneric("area"))
setClass("Shape", representation("VIRTUAL"))
setClass("Sq", contains = "Shape", representation(s = "numeric"))
setClass("Circ", contains = "Shape", representation(r = "numeric"))
setMethod("area", "Sq", function(shape, ...) shape@s^2)
setMethod("area", "Circ", function(shape, ...) pi * shape@r^2)
area(new("Sq", s = 3))
area(new("Circ", r = 1))
r <- tryCatch(area(1), error = function(e) conditionMessage(e))
r
setGeneric("f", function(x, text = "default") standardGeneric("f"))
setClass("B0", representation(s0 = "numeric"))
setClass("B1", contains = "B0")
setMethod("f", "B0", function(x, text = "B0 method") paste(text, ":", class(x)))
setMethod("f", "B1", function(x, text = "B1 method") callNextMethod())
f(new("B0", s0 = 1))
f(new("B1", s0 = 1))
f(new("B1", s0 = 1), "given")
setGeneric("g", function(x, y) standardGeneric("g"))
setMethod("g", signature("numeric", "missing"), function(x, y) "numeric, missing")
setMethod("g", signature("numeric", "character"), function(x, y) "numeric, character")
setMethod("g", signature("ANY", "ANY"), function(x, y) "ANY, ANY")
g(1)
g(1, "a")
g("a", 1)
setMethod("show", "Sq", function(object) cat("<Sq", object@s, ">\n"))
new("Sq", s = 2)
print(new("Sq", s = 5))
list(new("Sq", s = 1))
setMethod("length", "Sq", function(x) 4L)
length(new("Sq", s = 1))
setMethod("[", "Sq", function(x, i, ...) x@s * i)
new("Sq", s = 2)[3]
setMethod("Arith", signature("Sq", "numeric"), function(e1, e2) new("Sq", s = callGeneric(e1@s, e2)))
new("Sq", s = 2) * 5
isGeneric("area")
showMethods("area")
removeMethod("area", "Circ")
existsMethod("area", "Circ")
