# class unions, validity, slot assignment checks, multiple dispatch, virtual classes, callNextMethod chains
library(methods)
setClassUnion("NumOrChar", c("numeric", "character"))
setClass("H", representation(v = "NumOrChar"))
new("H", v = 1)@v
new("H", v = "a")@v
r <- tryCatch(new("H", v = TRUE), error = function(e) conditionMessage(e)); cat(r, "\n")
setClass("Pos", representation(x = "numeric"), validity = function(object) if (any(object@x < 0)) "negative x" else TRUE)
r <- tryCatch(new("Pos", x = -1), error = function(e) conditionMessage(e)); cat(r, "\n")
p <- new("Pos", x = 1)
p@x <- -5
r <- tryCatch(validObject(p), error = function(e) conditionMessage(e)); cat(r, "\n")
r <- tryCatch(p@x <- "a", error = function(e) conditionMessage(e)); cat(r, "\n")
r <- tryCatch(p@y, error = function(e) conditionMessage(e)); cat(r, "\n")
setGeneric("sz", function(x) standardGeneric("sz"))
class(sz)
setMethod("sz", "ANY", function(x) length(x))
setMethod("sz", "character", function(x) sum(nchar(x)))
sz(1:3); sz(c("ab", "c"))
setGeneric("combine", function(x, y) standardGeneric("combine"))
setMethod("combine", signature("numeric", "numeric"), function(x, y) x + y)
setMethod("combine", signature("character", "ANY"), function(x, y) paste(x, y))
combine(1, 2); combine("a", 3)
r <- tryCatch(combine(TRUE, 1), error = function(e) conditionMessage(e)); cat(r, "\n")
setClass("Base", representation("VIRTUAL", id = "integer"))
r <- tryCatch(new("Base"), error = function(e) conditionMessage(e)); cat(r, "\n")
setGeneric("describe", function(obj) standardGeneric("describe"))
setClass("D1", contains = "Base"); setClass("D2", contains = "D1")
setMethod("describe", "Base", function(obj) "base")
setMethod("describe", "D1", function(obj) paste("d1 >", callNextMethod()))
describe(new("D2", id = 1L))
isVirtualClass("Base")
extends("D2")
