# introspection and printing: str, getClass, showMethods, getMethod, identical, all.equal, as(), selectMethod
library(methods)
setClass("Person", representation(name = "character", age = "numeric"), prototype(name = "?", age = NA_real_))
setGeneric("greet", function(obj, ...) standardGeneric("greet"))
setMethod("greet", "Person", function(obj, ...) cat("Hi", obj@name, "\n"))
p <- new("Person", name = "Ann", age = 30)
p
str(p)
isVirtualClass("Person")
getClass("Person")
showMethods("greet")
getMethod("greet", "Person")
existsMethod("greet", "Person")
hasMethod("greet", "Person")
slotNames(p)
getSlots("Person")
validObject(p)
identical(p, new("Person", name = "Ann", age = 30))
all.equal(p, new("Person", name = "Bob", age = 30))
is(p)
methods::is(p, "Person")
initialize(p, age = 31)@age
setClass("Student", contains = "Person", representation(school = "character"))
s <- new("Student", p, school = "X")
s@name
is(s, "Person")
as(s, "Person")
greet(s)
selectMethod("greet", "Student")
isGeneric("greet")
removeGeneric("greet")
exists("greet")
