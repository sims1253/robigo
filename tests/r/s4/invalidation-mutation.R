library(methods)
setClass("InvalidateBase", slots = c(x = "numeric"))
setClass("InvalidateChild", contains = "InvalidateBase")
setClass("InvalidateOther", slots = c(x = "numeric"))
setGeneric("readValue", function(x) standardGeneric("readValue"))
setMethod("readValue", "ANY", function(x) -1)
setMethod("readValue", "InvalidateBase", function(x) x@x)
a <- new("InvalidateChild", x = 2)
b <- new("InvalidateOther", x = 3)
print(c(readValue(a), readValue(a), readValue(b)))
setMethod("readValue", "InvalidateBase", function(x) x@x + 10)
print(c(readValue(a), readValue(b)))
setMethod("readValue", "InvalidateOther", function(x) x@x + 100)
print(c(readValue(a), readValue(b), readValue(a)))
setMethod("readValue", "InvalidateChild", function(x) x@x + 1000)
print(readValue(a))
print(removeMethod("readValue", "InvalidateChild"))
print(readValue(a))
print(removeMethod("readValue", "InvalidateBase"))
print(c(readValue(a), readValue(b)))
setClass("InvalidateLater", contains = "InvalidateOther")
print(readValue(new("InvalidateLater", x = 4)))
