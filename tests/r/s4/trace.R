# trace() with tracer expressions (methods' .TraceWithMethods, tracingState)
library(methods)
f <- function(x) x + 1
trace(f, quote(cat("hello\n")), where = environment())
f(3)
tracingState()
tracingState(FALSE)
f(4)
tracingState(TRUE)
untrace(f, where = environment())
f(5)
setGeneric("g", function(x) standardGeneric("g"))
setMethod("g", "numeric", function(x) x * 2)
trace("g", quote(cat("in g\n")), signature = "numeric")
g(2)
untrace("g", signature = "numeric")
g(2)
