# R_strtod5: digits accumulated (exactly) and scaled in long double
h <- function(v) cat(sprintf("%a", v), sep = "\n")
i <- 1:300
s <- c(sprintf("%.*f", i %% 18, sqrt(i) * 10^((i %% 11) - 5)), sprintf("%de%d", i, (i %% 40) - 20),
  "123456789012345678901234567890", "0.1234567890123456789012345", "9223372036854775807", "9223372036854775808",
  "92233720368547758079", "18446744073709551615", "18446744073709551616", "1e-310", "4.9e-324", "1.7976931348623157e308",
  "1e309", "-0", "  12  ", "0x1p-3", "0x1.8p1", "1.", ".5", "-.5e-2", "+3", "00000000000000000000000001.5",
  "0.000000000000000000000000000000000000001", "123456789.123456789123456789")
h(as.numeric(s))
