# Error messages of the character functions
err <- function(expr) tryCatch(expr, error = function(e) conditionMessage(e),
                               warning = function(w) paste("warning:", conditionMessage(w)))
err(nchar("abc", type = "foo"))
err(nchar("abc", type = ""))
err(nchar(factor("a")))
err(nzchar(factor("a")))
err(substr(1, 1, "a"))
err(substr("abc", integer(0), 1))
err({x <- 1; substr(x, 1, 1) <- "a"; x})
err(startsWith(1, "a"))
err(chartr("abc", "xy", "abc"))
err(chartr("c-a", "xyz", "abc"))
err(chartr(c("ab", "cd"), "xy", "abcd"))
err(chartr(NA, "x", "a"))
err(strtoi("1", 1))
err(strrep("x", -1))
err(make.unique(1))
err(make.unique("a", sep = c("a", "b")))
err(make.names("a", allow_ = NA))
err(basename(1))
err(utf8ToInt(1))
err(utf8ToInt(c("a", "b")))
err(intToUtf8(1, multiple = NA))
err(strtrim("abc", -1))
err(strtrim("abc", NA))
err(enc2utf8(1))
err(charToRaw(1))
err(charToRaw(c("a", "b")))
err(rawToChar(as.raw(c(0x41, 0, 0x42))))
err(rawToChar("a"))
err(encodeString(1))
err(encodeString("x", width = -1))
err(Encoding(1))
err(toupper(list()))
err(paste("a", sep = NA))
err(paste("a", collapse = character(0)))
err(paste("a", recycle0 = NA))
err(paste(sum))
err(file.path("a", fsep = 1))
err(format(1, nsmall = 21))
err(format(1, digits = 23))
err(format(1, width = NA))
err(formatC(1, width = 0))
err(formatC(1, mode = "foo"))
err(formatC(1, format = "z"))
err(formatC(1, flag = "x"))
err(iconv("x", "UTF-8", "NOPE"))
