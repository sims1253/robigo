# Connections write a string's bytes as they are; a text connection's
# lines keep those bytes, marked UTF-8 in a UTF-8 locale (C after that).
x <- "\xe9t\xe9"
u <- iconv(intToUtf8(233), "UTF-8", "latin1")
con <- textConnection("z", "w")
writeLines(c(x, u, "a"), con)
cat(x, file = con)
close(con)
print(lapply(z, charToRaw))
print(Encoding(z))
tc <- textConnection("y", "w")
sink(tc)
cat(x, "\n")
cat(u, "\n")
sink()
close(tc)
print(lapply(y, charToRaw))
print(Encoding(y))
f <- tempfile()
fc <- file(f, "w")
writeLines(c(x, u), fc)
cat(x, "\n", file = fc)
close(fc)
print(readBin(f, "raw", 30))
sink(f)
cat(x, u, "\n")
print(x)
sink()
print(readBin(f, "raw", 30))
rc <- rawConnection(raw(0), "w")
writeLines(c(x, u), rc)
cat(x, file = rc)
print(rawConnectionValue(rc))
close(rc)
