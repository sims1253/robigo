# In a locale that is not UTF-8, strings marked UTF-8 or latin1 print
# translated to the native encoding, with <U+XXXX> and <xx> for what it
# cannot represent (issue #237).
invisible(Sys.setlocale("LC_CTYPE", "C"))
print(l10n_info()[c("MBCS", "UTF-8", "Latin-1")])
u <- intToUtf8(c(99, 97, 102, 233))
l <- iconv(u, "UTF-8", "latin1")
n <- rawToChar(as.raw(c(0x63, 0x61, 0x66, 0xc3, 0xa9)))
e <- intToUtf8(c(0x20ac, 0x1f600))
print(Encoding(c(u, l, n, e)))
print(u); print(l); print(n); print(e)
print(c(u, "x")); print(c(u, "abcdefghijkl"))
print(c(u, "x"), quote = FALSE)
print(c(l, "x"))
x <- c(1, 22); names(x) <- c(u, "b"); print(x)
m <- matrix(c(u, "x", "yy", "z"), 2); print(m); print(m, right = TRUE)
dimnames(m) <- list(c(u, "r"), c("a", l)); print(m)
print(list(a = u, b = l))
# format() translates and pads by the escaped width
print(format(c(u, "x"))); print(format(c(l, "x"))); print(format(c(u, "x"), width = 14))
print(format(c(u, "abcdefghijklmn"), justify = "right"))
print(Encoding(format(c(u, "x")))); print(nchar(format(u, width = 12)))
print(formatC(c(u, "x"), width = 12))
# encodeString() keeps UTF-8 strings UTF-8 and escapes them
print(encodeString(u)); print(encodeString(c(u, "x")))
print(encodeString(c(u, "x"), quote = '"'))
print(encodeString(c(l, "x"), quote = '"'))
print(encodeString(n)); print(encodeString(e))
print(nchar(encodeString(c(u, "xxxxxxxxxxxxxxxxx"), width = NA)))
print(Encoding(encodeString(c(u, l))))
s <- c(u, e, "a\tb", "q\"", intToUtf8(0x7f), intToUtf8(0x85))
print(s); print(encodeString(s))
# cat() writes the translation
cat(u, l, n, e, "\n")
cat(s, sep = "|"); cat("\n")
cat(u, l, sep = intToUtf8(0xe0)); cat("\n")
cat(c(u, "x"), fill = 12)
# dput() and deparse()
dput(u); dput(l); dput(s)
print(deparse(u)); print(deparse(c(u, l)))
f <- factor(c(u, "x")); print(f)
