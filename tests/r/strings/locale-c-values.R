# Strings that deparse, format, paste and the condition system return in
# the C locale: their bytes and marks (charToRaw, Encoding).
invisible(Sys.setlocale("LC_CTYPE", "C"))
u <- intToUtf8(233)
l <- iconv(u, "UTF-8", "latin1")
show <- function(label, v) { cat(label, ": "); print(charToRaw(v[1])); print(Encoding(v)) }
cap <- function(expr) {
  out <- NULL
  tc <- textConnection("out", "w", local = TRUE)
  sink(tc); force(expr); sink(); close(tc)
  out
}
show("deparse u", deparse(u))
show("deparse l", deparse(l))
show("deparse call", deparse(call("f", x = u)))
show("as.character call", as.character(call("f", u, call("g", u)))[3])
show("dput capture", cap(dput(u)))
show("print capture", cap(print(u)))
show("format u", format(u))
show("format l", format(l))
show("format padded", format(c(u, "abcdefghij")))
show("formatC", formatC(u, width = 4))
show("encodeString", encodeString(u))
show("encodeString q", encodeString(u, quote = '"'))
show("toString", toString(c(u, "a")))
show("paste u", paste(u, "a"))
show("paste l", paste(l, "a"))
show("paste l collapse", paste(c(l, "b"), collapse = "+"))
show("paste0 ascii", paste0("a", "b"))
show("sprintf", sprintf("%s!", u))
show("sQuote", sQuote(u, FALSE))
show("gettextf", gettextf("x %s", u))
e <- tryCatch(stop(u), error = function(e) e)
