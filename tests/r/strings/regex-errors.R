# Regular expression compile errors and argument warnings
err <- function(expr) tryCatch(expr, error = function(e) conditionMessage(e),
                               warning = function(w) paste("warning:", conditionMessage(w)))
err(regexpr("(", "x"))
err(regexpr("[", "x"))
err(regexpr("a{2,1}", "x"))
err(regexpr("a{1", "x"))
err(regexpr("a**", "x"))
err(regexpr("[[:foo:]]", "x"))
err(regexpr("\\", "x"))
err(regexpr("(a)\\2", "x"))
err(regexpr("[b-a]", "x"))
err(regexpr("[[.a.]]", "x"))
err(regexec("(", "x"))
err(regexpr("(", "x", perl = TRUE))
err(regexpr("a[", "x", perl = TRUE))
err(regexpr("*a", "x", perl = TRUE))
err(regexpr("a)", "x", perl = TRUE))
err(regexpr("\\", "x", perl = TRUE))
err(gsub("", "x", "abc", fixed = TRUE))
err(grep(c("a", "b"), "abc"))
err(grep("a", "abc", fixed = TRUE, ignore.case = TRUE))
err(grep("a", "abc", fixed = TRUE, perl = TRUE))
err(sub("a", c("x", "y"), "abc"))
err(regexpr(NA, "abc"))
err(regexpr(character(0), "abc"))
err(strsplit(1, "a"))
err(strsplit("a", "(", perl = TRUE))
err(grepl("a", "b", perl = NA))
err(sub("a", "b", "c", fixed = c(TRUE, FALSE)))
err(sub(1, 2, 3))
tryCatch(regexpr("(", "x"), error = function(e) print(conditionCall(e)))
