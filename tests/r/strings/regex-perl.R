sub("a|ab", "X", "abc", perl = TRUE)
gsub("\\ba", "X", "aaa", perl = TRUE)
gsub("(?<=a)a", "X", "aaa", perl = TRUE)
gsub("a(?=b)", "X", "abac", perl = TRUE)
gsub("a(?!b)", "X", "abac", perl = TRUE)
gsub("(?<!a)b", "X", "abcb", perl = TRUE)
