gsub("(?i)HELLO", "bye", "Hello hello", perl = TRUE)
gsub("\\s{2,}", " ", "a  b   c", perl = TRUE)
gsub("(a)(?:b)(c)", "\\2\\1", "abc", perl = TRUE)
