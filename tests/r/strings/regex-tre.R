# Extended (TRE) regular expressions: grep, grepl, sub, gsub, regexpr,
# gregexpr, regexec
x <- c("apple", "banana", "cherry", NA, "date")
grep("an", x)
grep("an", x, value = TRUE)
grep("an", x, invert = TRUE)
grep("an", x, invert = TRUE, value = TRUE)
grepl("an", x)
grep("a", c(p = "x", q = "a", r = "ba"), value = TRUE)
grep(NA, c("a", "b"))
grep(NA, c("a", "b"), value = TRUE)
grepl(NA, "a")
grepl("^[A-Z]", c("Apple", "banana"))
grepl("a", c("A", "a"), ignore.case = TRUE)
grep("[[:digit:]]+", c("abc", "a1", "22"))
grepl("[[:alpha:]]", c("1", "a", "é"))
grepl("[[:space:]]", c("a b", "ab", "a\tb"))
grepl("[[:punct:]]", c("!", "a", "$", "_"))
grepl("[[:upper:]][[:lower:]]+", c("Hello", "hello", "HELLO"))
grepl("\\d", c("a1", "ab"))
grepl("\\w+@\\w+", c("me@home", "nope"))
grepl("[\\d]", c("d", "5", "\\"))
grepl("a.b", "a\nb")
grepl("x$", "x\n")
grepl("*a", "*a")
grepl(")", ")")
grepl("a{,}", "a")
grepl("^(ab)+$", c("abab", "aba"))
grepl("colou?r", c("color", "colour", "colr"))
grepl("^a.{2,3}z$", c("abz", "abbz", "abbbz", "abbbbz"))

sub("a", "A", "banana")
gsub("a", "A", "banana")
gsub("[aeiou]", "", "programming language")
sub("(\\w+) (\\w+)", "\\2 \\1", "hello world")
gsub("\\s+", " ", "too    many   spaces")
gsub("(^|_)([a-z])", "\\2", "snake_case_name")
sub("^\\s+|\\s+$", "", "  x  ")
gsub("^\\s+|\\s+$", "", "  x  ")
gsub("[[:space:]]+$", "", "trail   ")
sub("\\.[^.]*$", "", "file.tar.gz")
sub(".*/", "", "/a/b/c.txt")
sub("a|ab", "X", "abc")
gsub("(a)|b", "[\\1]", "ab")
gsub("a", "\\\\", "banana")
gsub("a", "\\0", "banana")
sub("(a)", "<\\1\\1>", "cat")
sub("(?i)A", "x", "a")
sub("A", "x", "aA", ignore.case = TRUE)
gsub("\\<a", "X", "aaa")
gsub("\\ba", "X", "aaa")
gsub("^a", "X", "aaa")
gsub("\\Ba", "X", "aaa")
gsub("a\\>", "X", "aaa")
gsub("", "-", "abc")
gsub("x*", "-", "abc")
gsub("b*", "-", "abc")
sub("", "-", "abc")
gsub("\\b", "|", "ab cd")
gsub("\\B", "|", "ab cd")
gsub("(a+)(b+)", "<\\2\\1>", "aabbb ab")
sub("x", "y", c(a = "x1", b = "x2"))
gsub("a", NA, c("banana", "kiwi"))
gsub(NA, "x", c("a", "b"))
sub("a", "b", c("a", NA))
gsub("[^[:alnum:]]", "", "a-b_c d!e")
gsub("([[:upper:]])", " \\1", "camelCaseWord")

regexpr("na", "banana")
regexpr("a", c("banana", NA, "xyz"))
regexpr("B", "abc", ignore.case = TRUE)
regexpr("[0-9]+|[0-9]+\\.[0-9]+", "3.14")
regexpr("a+?", "aaa")
regexpr("a.*?b", "aXbYb")
regexpr("é", "café")
regexpr("é", "café", useBytes = TRUE)
regexpr("a", "café a")
gregexpr("na", "banana")
gregexpr("a", c("banana", NA, "x"))
gregexpr("x*", "abc")
gregexpr("[[:digit:]]+", c("12 abc 345", "none"))
gregexpr("", "abc")
regexec("(a)|(b)", "b")
regexec("x(a)?", "x")
regexec("(\\w+)@(\\w+)\\.com", c("me@site.com", "none", NA))
regexec("(a|ab)(c|bcd)(d*)", "abcd")
regexec("a.c", c("abc", "a.c"), fixed = TRUE)
