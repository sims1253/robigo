# sprintf error and warning messages
err <- function(expr) tryCatch(expr, error = function(e) conditionMessage(e))
wrn <- function(expr) withCallingHandlers(expr, warning = function(w) {
    cat("warning:", conditionMessage(w), "\n")
    invokeRestart("muffleWarning")
})
err(sprintf("%d", 3.5))
err(sprintf("%s %s", "a"))
err(sprintf("%d", "a"))
err(sprintf("%f", "a"))
err(sprintf("%s", 1:3, 1:2))
err(sprintf("%y", 1))
err(sprintf("%", 1))
err(sprintf(1))
err(sprintf("%*d", 3))
err(sprintf("%d", 2147483648))
err(sprintf("%5$s", "a"))
err(sprintf("%**d", 1, 2, 3))
err(sprintf("%s", quote(x)))
err(sprintf("%d", TRUE + 0.5))
err(sprintf("%ld", 1L))
wrn(sprintf("%s", "a", "b"))
wrn(sprintf("%s", "a", "b", "c"))
wrn(sprintf(c("%s", "%s"), "a", "b"))
