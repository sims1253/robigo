# c() keeps an NA name as NA (bind.c NewName returns the tag itself)
args <- list(1, 2, 3)
names(args) <- c("a", NA, "c")
x <- c(list(), args)
names(x)
is.na(names(x))
names(c(b = args))
y <- c(1, 2)
names(y) <- c(NA, "q")
names(c(y))
names(c(z = y))
names(c(list(n = 1)[0], args))
names(unlist(list(k = y)))
names(unlist(args))
