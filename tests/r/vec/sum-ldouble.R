# sum() and prod() accumulate sequentially in long double
x <- c(0.1, 1e16, -3.5, 1/3, -1e16, 2.5e-300, 7)
print(sum(x), digits = 17)
print(sum(c(x, NA, x), na.rm = TRUE), digits = 17)
print(sum(c(NA, x, NaN, x, NA), na.rm = TRUE), digits = 17)
sum(c(NA, NaN), na.rm = TRUE)
sum(numeric(0))
sum(c(1e308, 1e308))
sum(c(1e308, 1e308, -1e308))
sum(c(0.1, 0.2, 0.3)) == 0.6
print(sum(sin(1:1000)), digits = 17)
print(sum(1 / (1:10000)), digits = 17)
print(prod(1 + 1 / (1:1000)), digits = 17)
print(prod(c(1/3, NA, 3, 0.7), na.rm = TRUE), digits = 17)
prod(c(NA, NaN), na.rm = TRUE)
prod(numeric(0))
prod(c(1e300, 1e300, 1e-300))
prod(c(1e300, 1e300))
print(mean(sin(1:1000)), digits = 17)
print(mean(c(1e16, 1, -1e16, 3)), digits = 17)
print(cumsum(c(1e16, 1, 1, -1e16)), digits = 17)
print(tail <- cumsum(1 / (1:1000))[1000], digits = 17)
