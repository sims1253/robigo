# mapply/Map fast paths: inlinable FUN, argument matching, MoreArgs,
# substitute, dispatch and errors (dots[[j]][[k]] semantics)
f2 <- function(x, y) x + y
mapply(f2, 1:3, 4:6)
Map(f2, 1:3, 4:6)
mapply(f2, y = 1:3, x = 4:6)
mapply(function(y, x) x * 10 + y, 1:3, 4:6)
mapply(function(ab, cd) ab * 100 + cd, ab = 1:3, cd = 1:3)
mapply(function(xyz, w) xyz * 100 + w, xy = 1:3, 1:3)
mapply(function(x, y, z) x + y * z, 1:3, 4:6, MoreArgs = list(z = 100))
mapply(function(x, y, z) x + y * z, 1:3, MoreArgs = list(y = 4:6, z = 100))
mapply(function(x, z, y) x * 100 + z * 10 + y, 1:3, MoreArgs = list(z = 7, y = 2))
mapply(function(x, y = 10) x + y, 1:3)
mapply(function(x, ...) x * 2, 1:3)
mapply(function(x) x * 2, 1:3)
mapply(function(x) x > 2, 1:4)
Map(function(x) x %/% 2L, 1:4)
Map(function(s) s, c("a", "b"))
mapply(function(x, y) list(x, y), 1:2, c("a", "b"))
Map(function(x) x, list(1, "a", NULL, list(1:2)))
mapply(f2, c(a = 1, b = 2), c(10, 20))
mapply(f2, 1:3, 1:2)
mapply(f2, numeric(0), numeric(0))
mapply(function(x) x * 2, matrix(1:4, 2))
mapply(function(x) Re(x), (1 + 1i) * 1:3)
mapply(function(x) x, as.raw(1:3))
mapply(function(x) deparse(substitute(x)), 1:3)
mapply(function(x, y) deparse(substitute(x + y)), 1:2, 4:5)
mapply(function(x, y, z) deparse(substitute(y)), 1:2, 1:2, MoreArgs = list(z = 1))
v <- Vectorize(function(x, y) x * 10 + y)
v(1:3, 4:6)
g <- function() { s <- 0; for (i in 1:50) s <- s + sum(mapply(function(x, y) x * y, 1:10, 10:1)); s }
g()
