# rep() with each, times vectors and length.out, cut anywhere.
x <- c(1.5, 2.5, 3.5)
print(rep(x, each = 3))
print(rep(x, each = 3, length.out = 7))
print(rep(x, each = 2, length.out = 13))
print(rep(x, each = 0))
print(rep(x, times = c(2, 0, 3)))
print(rep(x, times = c(2L, 1L, 3L), length.out = 4))
print(rep(x, times = 1:6, each = 2))
print(rep(x, times = 1:6, each = 2, length.out = 10))
print(rep(c("a", NA, "c"), times = c(1, 4, 2)))
print(rep(list(1, "b"), times = c(2, 1)))
print(rep(c(TRUE, NA), each = 2, length.out = 3))
print(rep(1:3, times = c(0, 0, 0)))
print(rep(1:3, length.out = 0, each = 2))
print(rep(x, rep.int(4L, 3L)))
psum <- cumsum(c(0.27, 0.12, 0.12, 0.27, rep(0.02, 11)))
rs <- (1:60) / 61
print(sum(outer(psum, rs, "<")))
print(dim(outer(1:3, 1:4)))
