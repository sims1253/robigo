# mapply, Map, Reduce, Filter and forceAndCall over compact sequences (AC1),
# directly, in lists and through dots
mapply(function(a, b) a + b, 1:3, 4:6)
mapply(function(a, b) a + b, seq_len(3), seq_along(letters[1:3]))
Map(c, 1:2, 3:4)
Reduce(`+`, 1:5)
Reduce(`+`, 1:5, accumulate = TRUE)
Filter(function(x) x > 1, 1:3)
mapply(function(...) sum(...), list(1:3, 4:6), list(7:9, 10:12))
f <- function(...) mapply(function(x, y) x * y, ...)
f(1:3, 2:4)
mapply(rep, 1:3, 3:1)
mapply(function(x, y) x, 1:4, 1:2)
forceAndCall(2, function(a, b) a + b, 1:3, 4:6)
g <- function(...) forceAndCall(2, function(a, b) a + b, ...)
g(1:3, 4:6)
mapply(function(x, k) x^k, 1:3, MoreArgs = list(k = 1:3), SIMPLIFY = FALSE)
Map(function(x, y) x:y, 1:2, 3:4)
lapply(list(a = 1:3, b = 4:6), function(v) mapply(`+`, v, rev(v)))
