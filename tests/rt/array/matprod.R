# %*%, crossprod, tcrossprod (array.c do_matprod; reference BLAS for finite
# operands, the simple loops otherwise); a matrix is shown by its dim,
# dimnames and values (printMatrix is not ported)
show <- function(m) {
  cat(typeof(m), "|", dim(m), "\n")
  d <- dimnames(m)
  if (!is.null(d)) { if (!is.null(names(d))) print(names(d)); print(d[[1]]); print(d[[2]]) }
  print(as.vector(m))
}
