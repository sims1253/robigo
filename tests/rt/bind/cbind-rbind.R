# cbind / rbind (bind.c do_bind, cbind, rbind); a matrix is shown by its
# type, dim, dimnames and values (printMatrix is not ported)
show <- function(m) {
  cat(typeof(m), "|", dim(m), "\n")
  str <- dimnames(m)
  if (is.null(str)) cat("no dimnames\n") else { cat("rows:", if (is.null(str[[1]])) "NULL" else str[[1]], "\n"); cat("cols:", if (is.null(str[[2]])) "NULL" else str[[2]], "\n") }
  print(if (is.list(m)) c(m) else as.vector(m))
}
