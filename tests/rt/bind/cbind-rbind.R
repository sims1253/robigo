# S3 dispatch
cbind.foo <- function(..., deparse.level = 1) { cat("cbind.foo, deparse.level", deparse.level, "\n"); length(list(...)) }
o <- structure(1, class = "foo")
print(cbind(1, o))
print(cbind(o, 2, deparse.level = 2))
rbind.bar <- function(...) "rbind.bar"
print(rbind(structure(1, class = c("baz", "bar")), 2))
# a method gets deparse.level only when it was given, tagged
cbind.qux <- function(x, ...) list(nargs(), names(list(...)))
q <- structure(1, class = "qux")
r <- cbind(q); print(r[[1]]); print(r[[2]])
r <- cbind(q, 2, deparse.level = 0); print(r[[1]]); print(r[[2]])
rbind.qux <- function(...) sys.call()
print(rbind(q, 3))
