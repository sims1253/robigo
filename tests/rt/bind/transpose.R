# t.default (array.c do_transpose)
show <- function(m) {
  cat(typeof(m), "|", dim(m), "\n")
  d <- dimnames(m)
  if (is.null(d)) cat("no dimnames\n") else { print(names(d)); cat("rows:", if (is.null(d[[1]])) "NULL" else d[[1]], "\n"); cat("cols:", if (is.null(d[[2]])) "NULL" else d[[2]], "\n") }
  print(if (is.list(m)) c(m) else as.vector(m))
}
m <- matrix(1:6, 2, dimnames = list(c("a", "b"), c("x", "y", "z")))
show(t(m))
