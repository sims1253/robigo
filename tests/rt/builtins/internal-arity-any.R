# .Internal arity: a fixed-arity internal's checkArity (error(), against
# the context), except those whose C checks otherwise; one of any arity
# reads R_NilValue past its arguments
f <- function(e) tryCatch({ e; cat("ok\n") }, error = function(e) print(e), warning = function(w) print(w))
f(.Internal(options()))
f(.Internal(sprintf()))
f(.Internal(radixsort()))
