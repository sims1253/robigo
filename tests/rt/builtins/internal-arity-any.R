f(.Internal(sys.function()))
f(.Internal(sys.nframe()))
f(.Internal(sys.calls()))
f(.Internal(sys.frames()))
f(.Internal(sys.on.exit()))
f(.Internal(interruptsSuspended()))
f(.Internal(radixsort(TRUE)))
f(.Internal(radixsort(TRUE, FALSE)))
f(.Internal(order(TRUE)))
f(.Internal(pmin(TRUE)))
f(.Internal(radixsort(TRUE, FALSE, TRUE)))
f(.Internal(dyn.load()))
f(.Internal(dyn.load(1)))
f(.Internal(paste0()))
f(.Internal(paste0(list("a"), NULL, FALSE, 4)))
f(.Internal(nchar("a")))
f(.Internal(nchar("a", "chars", FALSE, NA, 5)))
f(.Internal(Sys.getenv()))
f(.Internal(identical(1)))
f(.Internal(gettext(NULL)))
f(.Internal(gettext(NULL, "a", TRUE, 4)))
