# cat(file = ) and dput(file = ) write through the connection: a path
# (cat's R code opens it, "w" or "a" for append), an open connection, a
# closed one (do_cat's switch_stdout opens it "wt" and cat_cleanup closes
# it again; dput opens it "w"). stdout() is R_OutputCon, the active sink.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) paste(deparse(conditionCall(e)), conditionMessage(e), sep = ": "))
f <- tempfile()
cat("a\n", "b\n", file = f, sep = "")
print(readLines(f))
con <- file(f, "w")
cat(1:3, "\n", file = con)
cat("more", 4.5, TRUE, "\n", file = con)
close(con)
print(readLines(f))
cat("x\n", file = f, append = TRUE)
print(readLines(f))
cat("y", "z", file = f, sep = "\n", append = TRUE)
print(readLines(f))
# a closed connection: opened for the call and closed after
con <- file(f)
cat("closed", "\n", file = con)
print(isOpen(con))
print(readLines(f))
close(con)
# fill and labels through a file
cat(paste0("w", 1:12), file = f, fill = 20, labels = c("L1:", "L2:"))
print(readLines(f))
# a read-only connection
con <- file(f, "r")
print(msg(cat("no", file = con)))
close(con)
print(msg(cat("no", file = stdin())))
print(msg(cat("no", file = 99L)))
# an error in the middle: what came before is written, the connection closed
con <- file(f)
print(msg(cat("before", list(1), "after", file = con)))
print(isOpen(con))
close(con)
print(readLines(f, warn = FALSE))
# dput to a path, an open and a closed connection
dput(list(a = 1, b = "x"), file = f)
print(readLines(f))
con <- file(f, "w")
dput(1:3, con)
dput(c(x = 2.5), con)
close(con)
print(readLines(f))
con <- file(f)
dput("closed", con)
print(isOpen(con))
close(con)
print(readLines(f))
con <- file(f, "r")
print(msg(dput(1, con)))
close(con)
dput("to stderr", stderr())
# stdout() under a sink is the sink's connection
g <- tempfile()
sink(g)
s <- stdout()
cat("sunk\n")
cat("sunk too\n", file = stdout())
dput("dput sunk", stdout())
sink()
print(class(s))
print(s == stdout())
print(readLines(g))
# stderr() writes through the message sink
h <- tempfile()
m <- file(h, "w")
sink(m, type = "message")
cat("cat to stderr\n", file = stderr())
dput("dput to stderr", stderr())
writeLines("writeLines to stderr", stderr())
sink(type = "message")
close(m)
print(readLines(h))
print(class(stdout()))
print(class(stdin()))
print(class(stderr()))
