# pushBack, pushBackLength, clearPushBack (connections.c): pushed lines are
# read first, data[1] first; newLine; a partial read of a pushed line; the
# incomplete final line a non-blocking connection pushes back
# (isIncomplete); and the errors.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
f <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-pushback-", Sys.getpid())
writeLines(c("one", "two"), f)
con <- file(f, "r")
pushBack(c("a", "b"), con)
print(pushBackLength(con))
print(readLines(con, 1))
print(pushBackLength(con))
pushBack("c", con, newLine = FALSE)
print(readLines(con, 2))
print(pushBackLength(con))
pushBack(c("p", "q", "r"), con)
print(pushBackLength(con))
clearPushBack(con)
print(pushBackLength(con))
clearPushBack(con)
pushBack(character(0), con)
print(pushBackLength(con))
pushBack("", con, newLine = FALSE)
print(pushBackLength(con))
print(readLines(con, 1))
pushBack(c("x", NA), con)
print(readLines(con))
print(isIncomplete(con))
print(msg(pushBack(1, con)))
print(msg(pushBack("a", con, newLine = NA)))
print(msg(pushBack("a", 99)))
print(msg(pushBackLength(99)))
print(msg(clearPushBack(99)))
print(msg(isIncomplete(1)))
close(con)
con <- file(f, "rb")
print(msg(pushBack("a", con)))
close(con)
con <- file(f)
print(msg(pushBack("a", con)))
close(con)
con <- file(f, "w")
print(msg(pushBack("a", con)))
pushBack("z", con)
close(con)
print(file.remove(f))
# a non-blocking connection keeps an incomplete line for the next read
d <- if (dir.exists("data")) "data" else "tests/rt/connections/data"
f <- file.path(d, "incomplete.txt")
con <- file(f, "r", blocking = FALSE)
print(readLines(con))
print(isIncomplete(con))
print(pushBackLength(con))
print(readLines(con))
print(isIncomplete(con))
close(con)
con <- file(f, blocking = FALSE)
print(readLines(con))
print(isIncomplete(con))
print(pushBackLength(con))
print(isOpen(con))
close(con)
