# readLines (connections.c's do_readLines): n, ok, warn, an incomplete
# final line, CR and CRLF line ends, embedded NULs and skipNul, the UTF-8
# BOM, encoding marks, a connection it opens and closes, and its errors.
f <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-readlines-", Sys.getpid())
msg <- function(expr) sub(f, "F", tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e),
                                           warning = function(w) paste("warning:", conditionMessage(w))), fixed = TRUE)
writeLines(c("one", "two", "three"), f)
d <- if (dir.exists("data")) "data" else "tests/rt/connections/data"
print(readLines(f))
print(readLines(f, n = 2))
print(readLines(f, n = 0))
print(readLines(f, n = -5))
print(readLines(f, n = 2.9))
print(msg(readLines(f, n = 5, ok = FALSE)))
print(readLines(f, n = 5))
print(msg(readLines(f, n = NA)))
print(msg(readLines(f, n = "a")))
print(msg(readLines(f, n = NULL)))
print(msg(readLines(f, ok = NA)))
print(msg(readLines(f, warn = NA)))
print(msg(readLines(f, encoding = c("a", "b"))))
print(msg(readLines(f, skipNul = NA)))
print(msg(readLines(42)))
# a connection opened before: reads continue, it stays open
con <- file(f, "r")
print(readLines(con, n = 1))
print(readLines(con, n = 1))
print(isOpen(con))
print(readLines(con))
print(readLines(con))
close(con)
# one it opens is closed again
con <- file(f)
print(readLines(con, 1))
print(isOpen(con))
print(summary(con)$mode)
close(con)
# a write-only connection
con <- file(f, "a")
print(msg(readLines(con)))
close(con)
# the incomplete last line
g <- file.path(d, "incomplete.txt")
print(sub(d, "D", msg(readLines(g)), fixed = TRUE))
print(suppressWarnings(readLines(g)))
print(readLines(g, warn = FALSE))
print(readLines(file.path(d, "crlf.txt")))
g <- file.path(d, "nul.txt")
print(msg(readLines(g)))
print(suppressWarnings(readLines(g)))
print(readLines(g, skipNul = TRUE))
print(readLines(g, warn = FALSE))
x <- readLines(file.path(d, "bom.txt"))
print(nchar(x, "bytes"))
x <- readLines(file.path(d, "bom-only.txt"), warn = FALSE)
print(nchar(x, "bytes"))
g <- file.path(d, "utf8.txt")
print(Encoding(readLines(g)))
print(Encoding(readLines(g, encoding = "UTF-8")))
print(Encoding(readLines(g, encoding = "latin1")))
print(Encoding(readLines(g, encoding = "bytes")))
g <- file.path(d, "empty.txt")
print(readLines(g))
print(msg(readLines(g, 1, ok = FALSE)))
# gzfile: the incomplete last line is not pushed back
gz <- gzfile(f, "w")
writeLines(c("x", "y"), gz)
close(gz)
print(readLines(gzfile(f)))
print(file.remove(f))
print(msg(readLines(f)))
