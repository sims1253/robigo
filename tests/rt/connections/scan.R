# scan (scan.c's do_scan, scanVector, scanFrame, fillBuffer, scanchar) of
# character data: white space or a separator, quotes, comments, strip.white,
# skip, nlines, nmax, na.strings, fill, flush, multi.line, escapes, text =,
# an open connection, the messages (stderr) and warnings, and the errors.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
d <- if (dir.exists("data")) "data" else "tests/rt/connections/data"
g <- file.path(d, "glyphs.txt")
w <- file.path(d, "words.txt")
# tools' Adobe_glyphs read
a <- scan(g, what = list(adobe = "", unicode = ""), quiet = TRUE, sep = ";", comment.char = "#")
print(a)
print(scan(g, what = list("", NULL), sep = ";", comment.char = "#"))
print(scan(g, what = "", sep = ";", comment.char = "#", strip.white = TRUE))
print(scan(g, what = "", sep = ";", comment.char = "#", strip.white = TRUE, nmax = 3))
print(scan(g, what = "", sep = ";", skip = 2, nlines = 2))
print(scan(g, what = "", sep = "\n", quote = ""))
print(scan(g, what = "", sep = ";", comment.char = "#", flush = TRUE))
print(scan(w, what = character()))
print(scan(w, what = character(), quote = ""))
print(scan(w, what = character(), na.strings = c("beta", "NA")))
print(scan(w, what = character(), blank.lines.skip = FALSE, sep = "\n"))
print(scan(w, what = list("", ""), fill = TRUE))
print(scan(w, what = list("", "")))
print(msg(scan(w, what = list("", ""), multi.line = FALSE)))
print(scan(text = "x y\n'z w'", what = character(), quiet = TRUE))
x <- scan(text = "café b", what = character(), quiet = TRUE)
print(Encoding(x))
print(scan(text = "a\\tb c\\x41 \\101", what = character(), quiet = TRUE, allowEscapes = TRUE))
print(scan(text = "a\\tb", what = character(), quiet = TRUE))
print(scan(text = "'open quote", what = character(), quiet = TRUE))
print(scan(text = "a,'b,c',,d", what = "", sep = ",", quiet = TRUE))
print(scan(text = "a,\"b\"\"c\",d", what = "", sep = ",", quiet = TRUE))
print(scan(text = "", what = character(), quiet = TRUE))
print(scan(file.path(d, "nul.scan"), what = ""))
print(scan(file.path(d, "nul.scan"), what = "", skipNul = TRUE))
con <- file(g, "r")
print(scan(con, what = "", sep = ";", nlines = 3, quiet = TRUE))
print(readLines(con, 1))
close(con)
print(msg(scan(g, what = list())))
print(msg(scan(g, what = "", sep = ";;")))
print(msg(scan(g, what = "", dec = "")))
print(msg(scan(g, what = "", strip.white = c(TRUE, FALSE))))
print(msg(scan(g, what = "", comment.char = "ab")))
print(msg(scan(g, what = "", allowEscapes = NA)))
print(msg(scan(g, what = "", quote = 1)))
print(msg(scan(g, what = "", na.strings = 1)))
print(msg(scan(g, what = sum)))
print(msg(.Internal(scan(file(g), "", -1L, "", ".", "", 0L, 0L, "NA", FALSE, FALSE, FALSE, TRUE, TRUE, TRUE, "", FALSE, c("a", "b"), FALSE))))
