# textConnection(open = "r") (connections.c's do_textconnection, newtext,
# text_fgetc): the strings, each followed by a newline, read by readLines
# and parse; already open; pushBack; summary; the encodings; a 0xFF byte
# (text_fgetc returns C's signed char, so it reads as the end); the errors.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
tc <- textConnection(c("one", "two", "", "four"))
print(class(tc))
print(isOpen(tc))
print(isOpen(tc, "w"))
s <- summary(tc)
print(s$description)
print(s$class)
print(s$mode)
print(s$text)
print(readLines(tc, 2))
pushBack("pushed", tc)
print(readLines(tc))
print(readLines(tc))
close(tc)
x <- c("a", "b")
tc <- textConnection(x)
print(summary(tc)$description)
close(tc)
tc <- textConnection(character(0))
print(readLines(tc))
close(tc)
tc <- textConnection(NA_character_)
print(readLines(tc))
close(tc)
tc <- textConnection("x <- 1; y <- x + 1\nprint(y)")
print(parse(tc))
close(tc)
# parse() reads the pushback first (R_ParseConn's Rconn_fgetc)
tc <- textConnection("b <- 2")
pushBack(c("a <- 1", "f(a)"), tc)
print(parse(tc))
close(tc)
tc <- textConnection("caf\xc3\xa9", encoding = "bytes")
print(nchar(readLines(tc), "bytes"))
close(tc)
tc <- textConnection("café", encoding = "UTF-8")
print(nchar(readLines(tc), "bytes"))
close(tc)
tc <- textConnection(c("a\xffb", "c"))
print(readLines(tc))
print(isIncomplete(tc))
close(tc)
print(msg(textConnection(1)))
print(msg(textConnection("a", open = "x")))
print(msg(.Internal(textConnection(NA_character_, "a", "r", globalenv(), 1L))))
print(msg(.Internal(textConnection("d", "a", c("r", "w"), globalenv(), 1L))))
print(msg(.Internal(textConnection("d", "a", "r", NULL, 1L))))
print(msg(.Internal(textConnection("d", "a", "r", 1, 1L))))
print(msg(.Internal(textConnection("d", "a", "r", globalenv(), NA_integer_))))
