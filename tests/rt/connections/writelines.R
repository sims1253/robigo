# writeLines (connections.c's do_writelines): a read-only connection that is
# open refuses and leaves the file as it was; one that is not open is opened
# in mode "wt" (documented), replacing the file; sep and useBytes as GNU R
# checks them. (The file is read back with parse(): its lines are symbols.)
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
f <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-writelines-", Sys.getpid())
writeLines(c("one", "two"), f)
con <- file(f, "r")
print(msg(writeLines("three", con)))
close(con)
print(parse(f))
con <- file(f)
writeLines("three", con)
print(parse(f))
print(msg(writeLines("a", sep = character(0))))
writeLines(c("a", "b"), sep = c("-", "+"))
cat("|\n")
print(msg(writeLines("a", useBytes = NA)))
print(msg(writeLines("a", useBytes = logical(0))))
print(msg(writeLines("a", useBytes = "yes")))
writeLines("a", useBytes = 2)
print(msg(.Internal(writeLines("a", 42, "\n", FALSE))))
print(msg(.Internal(writeLines("a", stdout(), 1, FALSE))))
print(msg(.Internal(writeLines(1, stdout(), "\n", FALSE))))
print(file.remove(f))
