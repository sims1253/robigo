f(u); f(u, usetz = TRUE)
f(u, "%OS3"); f(u, "%OS"); f(u, "%OS", digits = 2L); f(u, "%OS9 and %OS1"); f(u, "%H:%M:%OS6")
f(u, c("%d.%m.%Y", "%j %U %u %w")); u2 <- .Internal(as.POSIXlt(c(0, 1e9), "UTC")); f(u2, "%A %a %B %b %p %I %y %C %e %D %F %R %T %n%t%%")
