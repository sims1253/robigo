# errors and warnings after prepare_reset_tz have no call (its CTXT_CCODE context, call R_NilValue)
cc <- function(expr) tryCatch(expr, error = function(e) list(conditionMessage(e), conditionCall(e)), warning = function(w) list("W", conditionMessage(w), conditionCall(w)))
z <- .Internal(as.POSIXlt(0, "UTC")); z$sec <- numeric(0)
print(cc(.Internal(as.POSIXct(z, "UTC"))))
print(cc(.Internal(format.POSIXlt(z, "%Y", FALSE, 0L))))
print(cc(.Internal(format.POSIXlt(.Internal(as.POSIXlt(0, "UTC")), "", FALSE, 0L))))
print(cc(.Internal(format.POSIXlt(.Internal(as.POSIXlt(0, "UTC")), 1, FALSE, 0L))))
print(cc(.Internal(as.POSIXlt(0, 1))))
print(cc(.Internal(as.POSIXct(list(1), "UTC"))))
b <- "x\xe9"; Encoding(b) <- "bytes"
print(cc(.Internal(strptime(b, "%Y", "UTC"))))
print(cc(.Internal(strptime("2000", b, "UTC"))))
print(cc(.Internal(strptime("2000-01-01", "%Y-%m-%d %Ez", "UTC"))))
print(cc(.Internal(format.POSIXlt(.Internal(as.POSIXlt(0, "UTC")), b, FALSE, 0L))))
print(cc(.Internal(format.POSIXlt(.Internal(as.POSIXlt(0, "UTC")), "%Y", FALSE, "x"))))
Sys.setenv(TZ = strrep("x", 1001)); str(cc(.Internal(as.POSIXlt(0, "Europe/Berlin")))); Sys.unsetenv("TZ")
