# coerce.c's call (do_call), a special: the call to `name` with the other
# arguments evaluated, their tags kept.
print(call("round", 10.5))
print(call("f", a = 1, b = "x", 1:3))
x <- 5; print(call("g", x, x + 1))
print(eval(call("sum", 1, 2, 3)))
nm <- "paste"; print(call(nm, "a", "b"))
print(call("f"))
print(class(call("f")))
print(typeof(call("f", NULL)))
print(length(call("f", NULL)))
print(identical(call("f", NULL)[[2]], NULL))
cl <- call("list", quote(a)); print(cl); print(eval(cl, list(a = 7)))
v <- 1:3; cv <- call("h", v); cv[[2]][1] <- 9L; print(v)
print(call(name = "f", 1))
print(call(na = "f", 1))
print(call("`odd name`", 1))
f <- function(...) tryCatch(..., error = function(e) list(conditionMessage(e), conditionCall(e)))
print(f(call()))
print(f(call(1)))
print(f(call(c("a", "b"))))
print(f(call(NA_character_)))
print(f(call("")))
print(f(call(".Internal", 1)))
print(f(call(nme = "f")))
print(f(call(strrep("a", 10001))))
print(f(call("f", stop("evaluated"))))
g2 <- function(...) call("f", ...)
print(f(g2(1)))
print(f(call(stop("first"))))
