# tempdir() and tempfile(): their shape (the names differ per run)
d <- tempdir()
grepl("/Rtmp[A-Za-z0-9]{6}$", d); dir.exists(d); identical(d, Sys.getenv("R_SESSION_TMPDIR"))
identical(tempdir(), d); identical(tempdir(check = TRUE), d)
f <- tempfile(); identical(dirname(f), d); grepl("^file[0-9a-f]+$", basename(f)); file.exists(f)
g <- tempfile(c("a", "bb"), fileext = c(".txt", ".csv", ".R"))
length(g); grepl("^(a|bb)[0-9a-f]+\\.(txt|csv|R)$", basename(g)); substr(basename(g), 1, 1)
h <- tempfile("x", tmpdir = c("/nowhere", "/elsewhere")); dirname(h)
length(unique(tempfile(rep("", 3))))
tempfile("p", "/q", "") != tempfile("p", "/q", "")
# errors, in do_tempfile's order
tryCatch(tempfile(1), error = function(e) conditionMessage(e))
tryCatch(tempfile(tmpdir = 1), error = function(e) conditionMessage(e))
tryCatch(tempfile(fileext = 1), error = function(e) conditionMessage(e))
tryCatch(tempfile(character(0)), error = function(e) conditionMessage(e))
tryCatch(tempfile(tmpdir = character(0)), error = function(e) conditionMessage(e))
tryCatch(tempfile(fileext = character(0)), error = function(e) conditionMessage(e))
tryCatch(tempdir(NA), error = function(e) conditionMessage(e))
tryCatch(tempdir(c(TRUE, FALSE)), error = function(e) conditionMessage(e))
tryCatch(.Internal(tempfile("a", "b")), error = function(e) conditionMessage(e))
# check = TRUE makes a new one when the old is no longer writable: gone,
# which no user can write to (a mode the owner cannot write still lets root)
file.remove(d); d2 <- tempdir(check = TRUE); d2 != d; grepl("/Rtmp[A-Za-z0-9]{6}$", d2); dir.exists(d2)
identical(Sys.getenv("R_SESSION_TMPDIR"), d2); identical(tempdir(), d2)
