# setwd (util.c's do_setwd) and file.rename (platform.c's do_filerename):
# the directory before, the rename's result and warnings, the errors.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e),
                               warning = function(w) paste("warning:", conditionMessage(w)))
d <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-wd-", Sys.getpid())
dir.create(d)
old <- getwd()
r <- withVisible(setwd(d))
print(r$visible)
print(identical(r$value, old))
print(basename(getwd()) == basename(d))
writeLines("a", "f1")
print(file.rename("f1", "f2"))
print(file.exists(c("f1", "f2")))
print(file.rename(c("f2", NA), c("f3", "f4")))
print(file.exists("f3"))
print(msg(file.rename("nosuch", "f5")))
print(suppressWarnings(file.rename(c("nosuch", "f3"), c("f5", "f6"))))
print(file.rename(character(), character()))
print(msg(file.rename("f6", c("a", "b"))))
print(msg(.Internal(file.rename(1, "a"))))
print(msg(.Internal(file.rename("a", 1))))
print(msg(file.rename("f6", "nodir/f7")))
print(file.remove("f6"))
print(identical(setwd(old), normalizePath(d)) || identical(basename(setwd(old)), basename(d)))
print(file.remove(d))
print(msg(setwd(d)))
print(msg(setwd(NA_character_)))
print(msg(setwd(character())))
print(msg(setwd(1)))
print(msg(.Internal(setwd(NULL))))
print(identical(getwd(), old))
