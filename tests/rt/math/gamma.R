# nmath's gamma family: values, their NaNs, and nmath's own warnings
print(gamma(c(0.5, 1, 1.5, 5, 10.5, -0.5, -1.5, 171, NA)), digits = 15)
print(lgamma(c(0.5, 1, 2, 10, 100, 1e5, -0.5, -2.5, NA)), digits = 15)
print(digamma(c(0.5, 1, 2, 10, -0.5, NA)), digits = 15)
print(trigamma(c(0.5, 1, 2, 10, -0.5, NA)), digits = 15)
gamma(c(0, -1, -2))
