# log's argument matching and its errors
# (the call and message; the missing-argument errors' classes are below)
show <- function(expr) tryCatch(expr,
    error = function(e) cat("Error in", deparse(conditionCall(e)), ":", conditionMessage(e), "\n"),
    warning = function(w) cat("Warning in", deparse(conditionCall(w)), ":", conditionMessage(w), "\n"))
show(log())
show(log(base = 2))
show(log(b = 2))
show(log(xx = 2))
show(log(1, 2, 3))
show(log(1, bas = 2, y = 3))
show(log(1, base = NULL))
show(log(x = 1, base = numeric(0)))
show(log(1, NULL))
show(log("a"))
show(log("a", 2))
show(log(1, "b"))
show(log2("a"))
show(log10(list(1)))
show(log2())
show(log2(1, 2))
show(log2(y = 1))
show(log(-1, 2))
log(x = 8, base = 2)
log(ba = 2, 8)
log(8, )
