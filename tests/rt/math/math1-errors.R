# errors: the call, verbatim messages
show <- function(expr) tryCatch(expr, error = function(e) print(e), warning = function(w) print(w))
show(floor("a"))
show(ceiling(list(1)))
show(exp(factor("a")))
show(sqrt(NULL))
show(floor())
show(floor(1, 2))
show(ceiling(y = 1))
show(trunc("a"))
show(trunc())
show(trunc(1+2i))
show(gamma(quote(x)))
floor(x = 2.5)
trunc(2.7, 3)
trunc(x = -2.7)
