# The namespace registry (envir.c): base's namespace, then a namespace
# made by hand as loadNamespace makes one (a `.__NAMESPACE__.` with its
# spec, exports and lazydata), registered, looked up with `::` and `:::`,
# imported from, and unregistered.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
# (the internals directly: base's R wrappers are not all bound before L5)
isloaded <- function(name) .Internal(isRegisteredNamespace(name))
isns <- function(e) .Internal(isNamespaceEnv(e))
print(isloaded("base"))
print(isns(.BaseNamespaceEnv))
print(isns(globalenv()))
print(identical(.Internal(getNamespaceRegistry())[["base"]], .BaseNamespaceEnv))
print(identical(base::sum, sum))
print(identical(base:::paste0, paste0))
print(msg(base::nonexistent_thing))
ns <- new.env()
info <- new.env()
assign("spec", c(name = "fakens", version = "1.0"), envir = info)
exports <- new.env()
assign("visible", "visible", envir = exports)
assign("renamed", "inner", envir = exports)
assign("exports", exports, envir = info)
lazydata <- new.env()
assign("lazy", 42, envir = lazydata)
assign("lazydata", lazydata, envir = info)
assign(".__NAMESPACE__.", info, envir = ns)
assign("visible", 1, envir = ns)
assign("inner", 2, envir = ns)
assign("hidden", 3, envir = ns)
print(isns(ns))
print(isloaded("fakens"))
.Internal(registerNamespace("fakens", ns))
print(isloaded("fakens"))
print(msg(.Internal(registerNamespace("fakens", ns))))
print(fakens::visible)
print(fakens::renamed)
print(fakens::lazy)
print(msg(fakens::hidden))
print(fakens:::hidden)
print(.Internal(getNamespaceValue("fakens", "hidden", FALSE)))
print(identical(.Internal(getRegisteredNamespace("fakens")), ns))
print(getNamespaceName(ns))
print(.Internal(environmentName(ns)))
print(identical(.Internal(topenv(ns, NULL)), ns))
inner <- new.env(parent = ns)
print(identical(.Internal(topenv(inner, NULL)), ns))
print(identical(.Internal(topenv(new.env(), NULL)), globalenv()))
imp <- new.env()
.Internal(importIntoEnv(imp, c("a", "b"), ns, c("visible", "hidden")))
print(get("a", envir = imp))
print(get("b", envir = imp))
print(msg(.Internal(importIntoEnv(imp, "a", ns, c("x", "y")))))
.Internal(unregisterNamespace("fakens"))
print(isloaded("fakens"))
print(msg(.Internal(unregisterNamespace("fakens"))))
print(is.null(.Internal(getRegisteredNamespace("fakens"))))
print(nchar(.Internal(internalsID())))
ns2 <- new.env()
info2 <- new.env()
assign("spec", c(name = "fakens2", version = "1.0"), envir = info2)
assign(".__NAMESPACE__.", info2, envir = ns2)
delayedAssign("quiet", invisible(42), assign.env = ns2)
.Internal(registerNamespace("fakens2", ns2))
.Internal(getNamespaceValue("fakens2", "quiet", FALSE))
