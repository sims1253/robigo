# The search path: attach() of a list, an environment and NULL at
# positions, search(), lookups through attached frames, detach().
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
# (GNU R's system profile attaches Autoloads: robigo-rt's M1 boot runs no
# profile yet, so the case starts without it)
if ("Autoloads" %in% search()) detach("Autoloads")
print(search())
a <- attach(list(alpha = 1, beta = "b"), name = "mylist")
print(search())
print(alpha)
print(ls(a))
print(environmentName(a))
e <- new.env()
assign("gamma", 3, envir = e)
assign("delta", 4, envir = e)
makeActiveBinding("act", function() "active!", e)
attach(e, pos = 3L, name = "myenv")
print(search())
print(gamma + delta)
print(act)
attach(NULL, name = "empty")
print(search())
print(msg(attach(list(1, 2), name = "bad")))
print(msg(attach(42, name = "bad")))
print(msg(attach(list(), name = "")))
alpha <- "global"
print(alpha)
print(get("alpha", pos = 3L))
d <- detach(pos = 3L)
print(ls(d))
print(search())
detach("empty")
detach("myenv")
print(search())
print(msg(detach(pos = 5L)))
