# options(keep.source =) (options.c): FALSE is the start-up value Common.R
# sets (keep.source = interactive()); setting it checks the value as GNU R
# does; parse(), source() and sys.source() read it (and keep.source.pkgs)
# in R, and nothing keeps source references. (source() itself needs
# utils' namespace, which robigo-rt cannot load yet.)
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
print(getOption("keep.source"))
print(getOption("keep.source.pkgs"))
old <- options(keep.source = FALSE)
print(old)
print(getOption("keep.source"))
print(msg(options(keep.source = NA)))
print(msg(options(keep.source = 1)))
print(msg(options(keep.source = c(FALSE, FALSE))))
print(msg(options(keep.source = "no")))
print(msg(options(keep.source = NULL)))
print(getOption("keep.source"))
options(keep.source.pkgs = FALSE)
print(getOption("keep.source.pkgs"))
f <- function(x) x + 1
print(attributes(f))
e <- parse(text = c("g <- function(y) {", "  y * 2", "}"))
print(attributes(e))
print(attributes(eval(e[[1]])))
p <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-keep-source-", Sys.getpid(), ".R")
writeLines(c("h <- function(z) {", "  # a comment", "  z", "}"), p)
env <- new.env()
sys.source(p, envir = env, keep.source = FALSE)
print(ls(env))
print(attributes(env$h))
print(deparse(env$h))
print(file.remove(p))
