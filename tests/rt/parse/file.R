# parse(file = ): a file read through a connection (opened and closed by
# parse, or open already), a missing final newline, and the errors.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
path <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-parse-", Sys.getpid(), ".R")
writeLines(c("x <- 1", "f <- function(a) a + x", "# a comment", "if (x > 0) \"pos\" else \"neg\""), path)
con <- file(path, "a")
writeLines("f(2)", con, sep = "")
close(con)
e <- parse(path)
print(length(e))
print(e)
for (ex in e) print(eval(ex))
con <- file(path, "r")
print(length(parse(con)))
close(con)
print(length(parse(path, n = 2)))
writeLines(c("a <- 1", "b c"), path)
print(inherits(tryCatch(parse(path), error = function(e) e), "error"))
print(file.remove(path))
print(msg(suppressWarnings(parse(file = "/nonexistent/robigo.R"))))
writeLines(c("one", "two"))
writeLines("three", sep = "|\n")
writeLines(c("p <- 1; q <- 2", "r <- 3", "s <- 4"), path)
con <- file(path, "r")
print(parse(con, n = 2))
print(parse(con, n = 1))
print(parse(con))
close(con)
# a syntax error stops the read at its token: an open connection keeps
# the rest
writeLines(c("1 + )", "42", "y y", "7"), path)
con <- file(path, "r")
print(inherits(tryCatch(parse(con, n = 1), error = function(e) e), "error"))
print(parse(con, n = 1))
print(inherits(tryCatch(parse(con), error = function(e) e), "error"))
print(parse(con))
close(con)
print(file.remove(path))
