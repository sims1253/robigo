# what parse(con, n = 1) leaves unread: the else lookahead read the token
rem <- function(txt) {
  f <- tempfile(); writeLines(txt, f, sep = "", useBytes = TRUE); con <- file(f, "r")
  r <- tryCatch({parse(con, n = 1); "ok"}, error = function(e) class(e)[1])
  cat(deparse(txt), r, "|", deparse(readLines(con, warn = FALSE)), "\n"); close(con)
}
rem("f(if(a) 1 |> 2\n^\r")
rem("f(if(a) 1 |> 2\n^ 3)\nNEXT\n")
rem("{if(a) 1 |> 2\n\"\\q\";TAIL\n")
rem("(if (TRUE) 1\n+ 2)\nNEXT\n")
rem("a::\nb\nNEXT\n")
rem("{a::\nb}\nNEXT\n")
rem("\\\n(x) x\nNEXT\n")
rem(paste0(strrep("(", 50), "1\nNEXT\n"))
rem(paste0("{", strrep("(", 48), "if(a) 1\nNEXT\n"))
rem("{if(a) 1\n+ 2}\nNEXT\n")
rem("(if (TRUE) 1\n)\nNEXT\n")
rem("{if (TRUE) 1\n\n}\nNEXT\n")
# a held end of input (a final CR) is read by the else lookahead
f <- tempfile()
writeLines("{if(TRUE) 1 |> 2\r", f, sep = "", useBytes = TRUE)
con <- file(f, "r")
print(tryCatch({parse(con, n = 1); "ok"}, error = function(e) class(e)[1]))
a <- file(f, "a"); writeLines("2", a); close(a)
print(readLines(con, warn = FALSE))
close(con)
