# gram.y's yylex decides where a newline is a token (#1058): its context
# stack ('{', '(', '[', and 'i' for an if body outside the top level), its
# EatLines (set after an operator, `if`, `else`, `{`, a condition's `)`,
# `function(...)`; cleared after a symbol, a constant, `)`, `]`, `}`) and
# the token an if body's newline reads to see whether it is `else` (pushed
# back when it is not). `::` eats no newline; the contextstack holds 49.
p <- function(txt) {
  r <- tryCatch({x <- parse(text = txt, keep.source = FALSE); paste(vapply(as.list(x), function(e) paste(deparse(e), collapse=" "), ""), collapse = " ;; ")},
    error = function(e) paste0("<", class(e)[1], "> ", conditionMessage(e)))
  cat(deparse(txt), "=>", r, "\n")
}
p("(if (TRUE) 1\n+ 2)")
p("f(if (a) 1\n^ 2)")
p("f(if(a) 1 |> 2\n^ 3)")
p("a::\nb")
p("{a::\nb}")
p("{if(a) 1 |> 2\n\"\\q\";TAIL\n")
p("{if (a) 1\nelse 2}")
p("{if (a) 1\n\n\nelse 2}")
p("if (a) 1\nelse 2")
p("{if (a) if (b) 1\nelse 2\nelse 3}")
p("f(if (a) 1\n, 2)")
p("f(if (a) 1\n)")
p("x[if (a) 1\n]")
p("{if (a) 1\n}")
p("\\\n(x) x")
p("f <- \\\n(x) x")
p("function(x)\n\nx")
p("while (a)\nb")
p("for (i in 1)\n\ni")
p("if (a)\n\nb")
p("if\n(a) b")
p("{ }\n+1")
p("x$\ny")
p("x@\ny")
p("x[[\n1\n]]")
p("x |>\nf()")
p("{if (a) 1 else\n2}")
p("repeat\nbreak")
p("function\n(x) x")
p("{function(x) if (a) 1\nelse 2}")
p("(function(x) if (a) 1\nelse 2)")
p("{if (a) {1}\nelse 2}")
p("{if (a) (1)\nelse 2}")
p("{if (a) f(1)\nelse 2}")
p("{if (a) x[1]\nelse 2}")
p("{if (a) 1; else 2}")
p(paste0(strrep("(", 60), "1", strrep(")", 60)))
p(paste0(strrep("(", 48), "1", strrep(")", 48)))
p(paste0(strrep("(", 49), "1", strrep(")", 49)))
p(paste0("{", strrep("(", 48), "if(a) 1", strrep(")", 48), "}"))
p("f(a=\n1)")
p("f(a\n=1)")
p("function(a\n=1) a")
p("-\n1")
p("{x <- \n 1}")
p("{1 ->\n x}")
