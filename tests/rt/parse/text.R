# parse(text = ): expressions, their count, encodings, and the grammar's
# errors with GNU R's messages.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
e <- parse(text = c("x <- 1; y <- x + 2", "f <- function(a, b = 2) a * b", "if (x) y else z"))
print(length(e))
print(e[[1]])
print(e[[4]])
print(class(e))
print(parse(text = "g(1)\nh(2)\nk(3)", n = 2))
print(length(parse(text = character())))
print(length(parse(text = "")))
print(parse(text = c("a", "  # a comment", "b")))
print(msg(parse(text = "a b")))
print(msg(parse(text = c("f(x,", ")) + 1"))))
print(msg(parse(text = "x <- ")))
print(msg(parse(text = "1 +* 2", srcfile = "mine.R")))
print(parse(text = quote(a + b)))
print(tryCatch(parse(text = "a", encoding = "nonsense"), warning = function(w) conditionMessage(w)))
print(identical(eval(parse(text = "1:3 * 2")[[1]]), c(2, 4, 6)))
print(parse(text = "1; 2 +", n = 1))
print(parse(text = c("a", "b c"), n = 1))
print(msg(parse(text = c("a", "b c"), n = 2)))
