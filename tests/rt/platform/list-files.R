# platform.c's list.files (do_listfiles, list_files) over a fixture tree.
d <- if (dir.exists("tests/rt/platform/listfiles")) "tests/rt/platform/listfiles" else "listfiles"
lf <- function(path = d, pattern = NULL, all.files = FALSE, full.names = FALSE, recursive = FALSE,
               ignore.case = FALSE, include.dirs = FALSE, no.. = FALSE, fixed = FALSE)
    .Internal(list.files(path, pattern, all.files, full.names, recursive, ignore.case, include.dirs, no.., fixed))
strip <- function(x) sub(d, "<d>", x, fixed = TRUE)
lf()
lf(all.files = TRUE)
lf(all.files = TRUE, no.. = TRUE)
lf(recursive = TRUE)
lf(recursive = TRUE, include.dirs = TRUE)
lf(recursive = TRUE, all.files = TRUE)
lf(recursive = TRUE, all.files = TRUE, include.dirs = TRUE, no.. = TRUE)
lf(pattern = "\\.Rd$")
lf(pattern = "\\.rd$", ignore.case = TRUE, recursive = TRUE)
lf(pattern = ".", fixed = TRUE)
lf(pattern = "^[a-z]", recursive = TRUE, include.dirs = TRUE)
lf(pattern = character(0))
strip(lf(full.names = TRUE))
strip(lf(full.names = TRUE, recursive = TRUE, pattern = "e"))
strip(lf(path = c(d, file.path(d, "sub")), full.names = TRUE))
lf(path = c(file.path(d, "nosuchdir"), NA))
lf(path = character(0))
lf(path = file.path(d, "a.txt"))
f <- function(...) tryCatch(lf(...), error = function(e) conditionMessage(e))
f(path = 1)
f(pattern = 1)
f(pattern = NA_character_)
f(pattern = "(")
f(all.files = NA)
f(full.names = NA)
f(recursive = NA)
f(ignore.case = NA)
f(include.dirs = NA)
f(no.. = NA)
f(fixed = NA, pattern = ".")
tryCatch(.Internal(list.files(d)), error = function(e) conditionMessage(e))
