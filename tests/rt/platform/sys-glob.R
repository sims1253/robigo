strip <- function(x) sub(d, "<d>", x, fixed = TRUE)
g <- function(paths, dirmark = FALSE) strip(.Internal(Sys.glob(paths, dirmark)))
g(file.path(d, "*"))
g(file.path(d, "*"), dirmark = TRUE)
g(file.path(d, "*.Rd"))
g(file.path(d, "[ab]*"))
g(file.path(d, "?.txt"))
g(file.path(d, "with space.txt"))
g(file.path(d, "nosuch*"))
g(file.path(d, "nosuchfile"))
g(d)
g(d, dirmark = TRUE)
g(c(file.path(d, "*.Rd"), NA, file.path(d, "*.txt")))
g(c(file.path(d, "*.txt"), file.path(d, "a*")))
g(NA_character_)
g(character(0))
g(file.path(d, "*"), dirmark = 1)
g(file.path(d, "sub", "*"))
g(file.path(d, "*", "*"))
typeof(.Internal(Sys.glob(character(0), NA)))
strip(Sys.glob(file.path(d, "*.Rd")))
