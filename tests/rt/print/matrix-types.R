# printMatrix for each type: the column formats, NA, quote and right
matrix(c(TRUE, NA, FALSE, TRUE, FALSE, NA), 2)
matrix(1:6, 2)
matrix(c(-5L, 100000L, NA, 3L), 2)
matrix(c(1.5, NA, 3, 100, -0.25, 1e-10), 2)
matrix(c(1e10, 1, 2, 3), 2)
matrix(c(NaN, Inf, -Inf, 0), 2)
matrix(c(pi, exp(1), sqrt(2), 1/3), 2)
print(matrix(c(pi, exp(1), sqrt(2), 1/3), 2), digits = 3)
matrix(c(1+2i, NA, -3i, 4, 1.5-0.5i, NaN), 2)
matrix(c(complex(real = NA, imaginary = 1), 1i), 1)
matrix(c("a", NA, "ccc", "d"), 2)
print(matrix(c("a", NA, "ccc", "d"), 2), quote = FALSE)
print(matrix(c("a", NA, "ccc", "d"), 2), right = TRUE)
print(matrix(c("a", NA, "ccc", "d"), 2), quote = FALSE, right = TRUE)
print(matrix(c("a", NA, "b", "c"), 2), na.print = "--")
print(matrix(c(1, NA, 3, 4), 2), na.print = "")
matrix(c("tab\there", "quote\"d", "back\\slash", "nl\nx"), 2)
matrix(as.raw(c(0, 1, 255, 16)), 2)
matrix(c(TRUE, FALSE), 1)
matrix(1:3, 3)
matrix(1:3, 1)
print(matrix(1:6, 2), print.gap = 3)
print(matrix(c("a", "b"), 1), print.gap = 0)
m <- matrix(c(1.123456789, 22.1, 333, 4444.5), 2)
m
print(m, digits = 2)
