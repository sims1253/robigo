# PrintInit reads digits, scipen, max.print and width from options()
x <- c(pi, exp(1))
options(digits = 3); x; matrix(x, 1)
options(digits = 7)
options(scipen = 5); c(1e6, 1e-6); options(scipen = 0); c(1e6, 1e-6)
options(scipen = -5); 100; options(scipen = 0)
options(width = 30); 1:30; options(width = 80)
options(max.print = 3); 1:10; list(1, 2, 3, 4, 5); options(max.print = 99999)
tryCatch(options(digits = 0), error = function(e) print(conditionMessage(e)))
tryCatch(options(width = 5), error = function(e) print(conditionMessage(e)))
options(deparse.cutoff = 20); quote(f(aaaaaaaa, bbbbbbbbb, ccccccccc, ddddddd)); options(deparse.cutoff = 60)
tryCatch(options(scipen = "a"), error = function(e) print(conditionMessage(e)))
tryCatch(options(scipen = 1e10), error = function(e) print(conditionMessage(e)))
withCallingHandlers(options(scipen = 100000), warning = function(w) { print(conditionMessage(w)); invokeRestart("muffleWarning") })
getOption("scipen"); options(scipen = 0)
