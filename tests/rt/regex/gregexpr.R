# gregexpr: every match, on TRE (bytes and wide), fixed strings and PCRE;
# empty matches, anchors, look-behind across matches and the attributes.
shw <- function(r) {
    for (a in c("capture.start", "capture.length")) {
        m <- attr(r, a)
        attr(r, a) <- NULL
        print(attr(m, "dim"))
        print(attr(m, "dimnames"))
        print(c(m))
    }
    print(r)
}
x <- c("banana", "apple", NA, "", "cherry")
print(gregexpr("an", x))
print(gregexpr("a", x))
print(gregexpr("x*", "abc"))
print(gregexpr("b*", "abbc"))
print(gregexpr("", "abc"))
print(gregexpr("^a", "aaa"))
print(gregexpr("a$", "aaa"))
print(gregexpr("\\<", "ab cd"))
print(gregexpr("é", "aéxé"))
print(gregexpr("", "éa"))
print(gregexpr("[[:alpha:]]+", "a1bb22ccc"))
print(gregexpr("aa", "aaaaa", fixed = TRUE))
print(gregexpr("é", "éaé", fixed = TRUE))
print(gregexpr("", "éa", fixed = TRUE))
print(gregexpr("a", x, fixed = TRUE))
print(gregexpr("a", x, perl = TRUE))
print(gregexpr("x*", "abc", perl = TRUE))
print(gregexpr("^a", "aaa", perl = TRUE))
print(gregexpr("(?<=a)b", "abab", perl = TRUE))
print(gregexpr("\\bc", "c cc c", perl = TRUE))
print(gregexpr("é", "éaé", perl = TRUE))
print(gregexpr("A", "aAa", ignore.case = TRUE))
print(gregexpr("A", "aAa", ignore.case = TRUE, perl = TRUE))
print(gregexpr("b", c(x = "abcb")))
print(gregexpr("a", character(0)))
shw(gregexpr("(?<x>a)(b)?", "abaxa", perl = TRUE)[[1]])
shw(gregexpr("(?<x>q)", "aba", perl = TRUE)[[1]])
r <- gregexpr("(a)", c("aa", NA, "b"), perl = TRUE)
print(lengths(r))
print(attributes(r[[2]]))
print(c(attr(r[[3]], "capture.start")))
