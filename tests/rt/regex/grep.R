# grep and grepl: TRE on bytes and wide characters, fixed strings, PCRE,
# value = TRUE with names, invert, NA and the argument checks.
x <- c(a = "banana", b = "apple", c = NA, d = "", e = "Cherry")
print(grep("an", x))
print(grep("an", x, value = TRUE))
print(grep("an", x, invert = TRUE))
print(grep("an", x, invert = TRUE, value = TRUE))
print(grepl("an", x))
print(grepl("^$", x))
print(grepl("c", x, ignore.case = TRUE))
print(grepl("[[:upper:]]", x))
print(grepl("(a)\\1", c("aa", "ab")))
print(grepl("é", c("é", "e", "xéy")))
print(grepl(".", c("é", ""), fixed = TRUE))
print(grepl("é", c("é", "e"), fixed = TRUE))
print(grepl("p+", x, perl = TRUE))
print(grepl("(?<=a)n", x, perl = TRUE))
print(grepl("\\d", c("a1", "b"), perl = TRUE))
print(grep(NA, x))
print(grep(NA, x, value = TRUE))
print(grepl(NA, x))
print(grep("a", character(0)))
print(grepl("a", character(0)))
print(grep("1", 1:12))
print(grepl("é", "é", useBytes = TRUE))
print(grepl("a", "aa", fixed = TRUE, ignore.case = TRUE))
print(grepl("a", "aa", fixed = TRUE, perl = TRUE))
print(grepl(c("a", "b"), "ab"))
try(grepl(character(0), "a"))
try(grepl("[", "a"))
try(grepl("(", "a", perl = TRUE))
try(grepl("a", c("ok", "\xffa")))
try(grepl("a", c("ok", "\xffa"), perl = TRUE))
print(grepl("a", c("ok", "\xffa"), useBytes = TRUE))
