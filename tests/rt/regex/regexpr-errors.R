# regexpr, gregexpr and regexec's errors and warnings, through try():
# arguments that are not strings, compilation errors, a zero-length
# fixed pattern, NA options and input invalid in the locale.
print(regexpr("a", "aa", fixed = TRUE, ignore.case = TRUE))
print(regexpr("a", "aa", fixed = TRUE, perl = TRUE))
print(gregexpr("a", "aa", fixed = TRUE, perl = TRUE))
print(regexpr(c("a", "b"), "ab"))
print(gregexpr(c("a", "b"), "ab"))
try(regexpr(character(0), "a"))
try(gregexpr(character(0), "a"))
try(regexec(character(0), "a"))
print(regexpr("1", 121))
print(regexec("1", 121))
try(regexpr("[", "a"))
try(gregexpr("[", "a"))
try(regexec("[", "a"))
try(regexpr("a{2,1}", "a"))
try(regexpr("(", "a", perl = TRUE))
try(gregexpr("(", "a", perl = TRUE))
try(regexec("(", "a", perl = TRUE))
try(regexpr("", "a", fixed = TRUE))
try(gregexpr("", "a", fixed = TRUE))
try(regexpr("a", "\xff"))
try(regexpr("a", c("ok", "\xffa")))
try(regexec("a", c("ok", "\xffa")))
try(regexpr("a", c("ok", "\xffa"), perl = TRUE))
try(regexpr("a", c("ok", "\xffa"), fixed = TRUE))
print(regexpr("a", c("ok", "\xffa"), useBytes = TRUE))
print(gregexpr("a", c("ok", "\xffa"), useBytes = TRUE))
try(regexpr("\xff", "a"))
try(regexec("\xff", "a"))
try(regexpr("a", "a", ignore.case = NA))
try(regexpr("a", "a", perl = NA))
print(regexec("a", "a", ignore.case = NA))
print(regexec("a", "a", fixed = NA))
try(regexpr(NA, "a"))
