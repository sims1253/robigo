# strsplit's errors and warnings, through try(): a split that is not a
# string, TRE's and PCRE's compilation errors, input invalid in the
# locale, and empty matches at the end of a string.
print(strsplit(as.character(pi), ".", fixed = TRUE))
print(strsplit("3.141592654", "[.]"))
try(strsplit(1, "a"))
try(strsplit("a", list()))
print(strsplit("a", 1))
try(strsplit("a", "["))
try(strsplit("a", "a{2,1}"))
try(strsplit("a", "(", perl = TRUE))
try(strsplit("a", "(?<", perl = TRUE))
try(strsplit("a", "\\"))
x <- c("a\xffb", "\xfe", "ok")
print(strsplit(x, ""))
print(strsplit(x, "b", useBytes = TRUE))
try(strsplit(x, "b"))
try(strsplit("a", "\xff"))
try(strsplit("a", "\xff", fixed = TRUE))
try(strsplit("a", "\xff", perl = TRUE))
y <- rep("\xff", 7)
print(strsplit(y, ""))
try(strsplit("a\u00e9", "\xe9"))
print(strsplit("abc", "c$"))
print(strsplit("abc", "^a"))
print(strsplit("aaa", "^a"))
print(strsplit("aaa", "^a", perl = TRUE))
print(strsplit("abab", "(?<=a)", perl = TRUE))
