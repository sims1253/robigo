# strsplit (grep.c:do_strsplit): ERE, fixed and PCRE splits, split = "" and NA,
# recycled split strings, names, and useBytes.
print(strsplit("a1b22c333", "[0-9]+"))
print(strsplit(c("abc", "héllo", NA), ""))
print(strsplit("a b", NA))
print(strsplit(c("a b", NA), NA_character_))
print(strsplit("a.b.c.", ".", fixed = TRUE))
print(strsplit("..a..", ".", fixed = TRUE))
print(strsplit("aébé", "é", fixed = TRUE))
print(strsplit("a1b2c", "\\d", perl = TRUE))
print(strsplit("abc", "(?=b)", perl = TRUE))
print(strsplit("héllo wörld", "\\s", perl = TRUE))
print(strsplit("héllo", "(?=l)", perl = TRUE))
print(strsplit(c("abc", "é"), "x*"))
print(strsplit("aébéc", "é"))
print(strsplit("a\U0001F600b", "x*"))
print(strsplit("a中b", "x*"))
print(strsplit("abc", "x*"))
print(strsplit("abc", "b*"))
print(strsplit(c("a-b", "c_d", "e-f"), c("-", "_")))
print(strsplit(c(x = "a b", y = "c d"), " "))
print(strsplit("héllo", "l", useBytes = TRUE))
print(strsplit("héllo", "", useBytes = TRUE))
print(strsplit("abc", character(0)))
print(strsplit(character(0), "a"))
print(strsplit("aabbcc", "(.)\\1"))
print(strsplit("a,b;c", "[,;]"))
print(strsplit("A1a1", "a", fixed = TRUE))
print(strsplit("one  two   three", " +"))
print(strsplit("x", "x"))
print(strsplit("", "x"))
print(strsplit("", ""))
print(strsplit("abc", "[[:alpha:]]"))
print(strsplit("ab12cd", "[[:digit:]]+", perl = TRUE))
print(strsplit("a b", " ", fixed = TRUE, perl = TRUE))
# the same, UTF-8-marked (\u escapes) instead of native
print(strsplit(c("abc", "h\u00e9llo"), ""))
print(strsplit("a\u00e9b\u00e9", "\u00e9", fixed = TRUE))
print(strsplit("h\u00e9llo w\u00f6rld", "\\s", perl = TRUE))
print(strsplit("h\u00e9llo", "", perl = TRUE))
print(strsplit("h\u00e9llo", "(?=l)", perl = TRUE))
print(strsplit(c("abc", "\u00e9"), "x*"))
print(strsplit("a\u00e9b", "x*", perl = TRUE))
print(strsplit("a\u00e9b", "x*", fixed = TRUE))
print(strsplit("h\u00e9llo", "l", useBytes = TRUE))
