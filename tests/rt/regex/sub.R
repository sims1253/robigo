# sub and gsub: TRE on bytes and on wide characters, fixed strings, PCRE
# with \U \L \E, empty matches, back-references and the attributes kept.
x <- c("banana", "apple", NA, "", "aaa")
print(sub("a", "X", x))
print(gsub("a", "X", x))
print(gsub("an", "<&>", x))
print(gsub("(a)(n)", "\\2\\1", x))
print(gsub("(a)|(p)", "[\\1\\2\\3]", x))
print(gsub("a", "\\0\\\\x\\", "banana"))
print(gsub("x*", "-", "abc"))
print(gsub("b*", "-", "abc"))
print(sub("x*", "-", "abc"))
print(gsub("", "-", "abc"))
print(gsub("^", "-", c("abc", "")))
print(gsub("$", "-", c("abc", "")))
print(gsub("^a", "X", "aaa"))
print(gsub("a$", "X", "aaa"))
print(gsub("\\b", "|", "ab cd"))
print(gsub("[[:space:]]+", " ", "  a \t b\n c  "))
print(gsub("[[:upper:]]", "u", "AbCd"))
print(gsub("A", "x", "aAa", ignore.case = TRUE))
print(sub("(b+)", "<\\1>", "abbbc"))
print(gsub("(a|b)*", "<\\1>", "abab c"))
print(gsub(".", "X", "a.b", fixed = TRUE))
print(gsub("aa", "b", "aaaaa", fixed = TRUE))
print(sub("aa", "b", "aaaaa", fixed = TRUE))
print(gsub("a", "", "banana", fixed = TRUE))
print(gsub("a", "\\1", "banana", fixed = TRUE))
print(gsub("a", NA, c("banana", "xyz", NA)))
print(gsub("a", NA, c("banana", "xyz"), fixed = TRUE))
print(gsub("a", NA, c("banana", "xyz"), perl = TRUE))
print(gsub(NA, "x", c("a", "b")))
print(gsub("(\\w+)", "\\U\\1", "hello world", perl = TRUE))
print(gsub("(\\w)(\\w*)", "\\U\\1\\L\\2", "hello WORLD", perl = TRUE))
print(gsub("(\\w)(\\w*)", "\\U\\1\\E\\2", "hello world", perl = TRUE))
print(gsub("(a)|(b)", "[\\1|\\2|\\9]", "abc", perl = TRUE))
print(gsub("x*", "-", "abc", perl = TRUE))
print(gsub("b*", "-", "abc", perl = TRUE))
print(gsub("", "-", "abc", perl = TRUE))
print(gsub("(?<=a)", "-", "banana", perl = TRUE))
print(gsub("\\d+", "#", c("a1b22c333", "none"), perl = TRUE))
print(sub("^\\s+|\\s+$", "", "  pad  ", perl = TRUE))
print(gsub("^\\s+|\\s+$", "", "  pad  ", perl = TRUE))
print(gsub("A", "x", "aAa", ignore.case = TRUE, perl = TRUE))
print(gsub("a", "X", "banana", useBytes = TRUE))
print(gsub("a", "X", "banana", perl = TRUE, useBytes = TRUE))
y <- c(first = "aXb", second = "XX")
print(gsub("X", "-", y))
m <- matrix(c("ab", "cb", "bb", "dd"), 2, dimnames = list(c("r1", "r2"), NULL))
r <- gsub("b", "B", m)
print(c(r))
print(attributes(r))
z <- structure(c("ab", "b"), class = "myclass", extra = 1)
print(unclass(sub("b", "", z)))
print(attributes(sub("b", "", z)))
# non-ASCII: TRE matches wide characters, PCRE and fixed UTF-8
u <- c("café", "naïve", "été")
print(gsub("é", "e", u))
print(gsub(".", "<&>", u[3]))
print(gsub("x*", "-", u[3]))
print(gsub("", "-", u[3], perl = TRUE))
print(gsub("x*", "-", u[3], perl = TRUE))
print(gsub("é", "E", u, fixed = TRUE))
print(gsub("(\\w+)", "\\U\\1", u, perl = TRUE))
print(gsub("(.)", "\\L\\1", "ÉTÉ", perl = TRUE))
print(gsub("[[:alpha:]]", "a", u))
print(gsub("E", "_", u, ignore.case = TRUE))
print(gsub("É", "_", u, ignore.case = TRUE))
print(sub("t", "é", "tot"))
print(gsub("t", "é", "tot", fixed = TRUE))
print(gsub("t", "é", "tot", perl = TRUE))
print(gsub("é", "e", u, useBytes = TRUE))
print(gsub("a", "b", c("abc", "café")))
print(nchar(gsub("(.)", "\\1\\1", u)))
