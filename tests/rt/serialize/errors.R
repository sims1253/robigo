# unserialize()'s and serialize()'s errors, with GNU R's messages.
msg <- function(expr) tryCatch({ force(expr); "no error" }, error = function(e) conditionMessage(e))
x <- serialize(list(1, "a"), NULL)
print(msg(unserialize(x[1:20])))
print(msg(unserialize(raw(0))))
print(msg(unserialize("x")))
print(msg(unserialize(as.raw(c(0x5a, 0x0a)))))
bad <- x
bad[6] <- as.raw(9)
print(msg(unserialize(bad)))
print(msg(serialize(1, NULL, version = 1L)))
print(msg(serialize(1, NULL, version = -1L)))
print(msg(serialize(1, 1, version = 2L)))
y <- serialize(quote(f(x)), NULL, version = 2L)
y[length(y) - 3] <- as.raw(99)
print(msg(unserialize(y)))
z <- serialize(1L, NULL, ascii = TRUE)
print(unserialize(z))
print(msg(unserialize(z[1:10])))
