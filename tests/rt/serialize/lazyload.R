# The lazy-load database's internals: values serialized, compressed and
# appended to a file, fetched back by key; flushing the cache.
path <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-lazyload-", Sys.getpid(), ".rdb")
vals <- list(1, "a", list(x = 1:2 + 0L), quote(f(y)), function(a) a)
keys <- lapply(vals, function(v) .Internal(lazyLoadDBinsertValue(v, path, FALSE, FALSE, NULL)))
print(keys[[1]])
print(keys[[2]])
back <- lapply(keys, function(k) lazyLoadDBfetch(k, path, FALSE, NULL))
print(identical(back, vals))
.Internal(lazyLoadDBflush(path))
ck <- .Internal(lazyLoadDBinsertValue(vals, path, FALSE, TRUE, NULL))
print(ck[1] == keys[[5]][1] + keys[[5]][2])
print(identical(lazyLoadDBfetch(ck, path, TRUE, NULL), vals))
.Internal(lazyLoadDBflush(path))
env <- new.env()
ek <- .Internal(lazyLoadDBinsertValue(list(env, env), path, FALSE, TRUE, function(e) "env::1"))
.Internal(lazyLoadDBflush(path))
got <- lazyLoadDBfetch(ek, path, TRUE, function(n) { cat("fetch hook", n, "\n"); env })
print(identical(got[[1]], env) && identical(got[[2]], env))
vars <- .Internal(getVarsFromFrame(c("vals", "path"), environment(), FALSE))
print(names(vars))
print(file.remove(path))
