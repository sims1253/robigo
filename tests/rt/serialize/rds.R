# saveRDS() and readRDS() through gzfile, file and gzcon connections:
# compressed or not, xdr or ascii, version 2 or 3; infoRDS; close's value.
path <- paste0(Sys.getenv("TMPDIR", "/tmp"), "/robigo-rt-rds-", Sys.getpid(), ".rds")
obj <- list(a = 1:3 + 0L, b = c(x = "y"), f = function(u) u, e = quote(g(h)))
saveRDS(obj, path)
print(identical(readRDS(path), obj))
str1 <- infoRDS(path)
print(str1)
saveRDS(obj, path, compress = FALSE)
print(identical(readRDS(path), obj))
saveRDS(obj, path, ascii = TRUE)
print(identical(readRDS(path), obj))
print(infoRDS(path)$format)
saveRDS(obj, path, version = 2)
print(infoRDS(path))
con <- gzfile(path, "rb")
print(class(con))
print(summary(con)$mode)
print(identical(readRDS(con), obj))
print(close(con))
con <- file(path, "rb")
gz <- gzcon(con)
print(class(gz))
print(identical(readRDS(gz), obj))
close(gz)
con <- file(path, "wb")
serialize(obj, con)
print(close(con))
con <- file(path, "rb")
print(identical(unserialize(con), obj))
close(con)
con <- file(path, "w")
serialize(c(1.5, NA), con)
close(con)
print(readRDS(path))
print(file.remove(path))
print(tryCatch(readRDS("/nonexistent/robigo.rds"), warning = function(w) conditionMessage(w)))
print(tryCatch(suppressWarnings(readRDS("/nonexistent/robigo.rds")), error = function(e) conditionMessage(e)))
print(tryCatch(saveRDS(1, ""), error = function(e) conditionMessage(e)))
