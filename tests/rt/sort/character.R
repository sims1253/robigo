# sort() and order() of strings: Scollate (ICU's root collator) for
# "shell", strcmp of the bytes for "radix", NA, decreasing, names
x <- c("b", "A", NA, "a", "B", "", "_x", "10", "9", "\u00e9", "e", "E", NA, "a")
print(sort(x))
print(sort(x, decreasing = TRUE))
print(sort(x, na.last = TRUE))
print(sort(x, na.last = FALSE, decreasing = TRUE))
print(sort(x, method = "radix"))
print(sort(x, method = "radix", decreasing = TRUE, na.last = TRUE))
print(order(x))
print(order(x, method = "radix"))
print(order(x, decreasing = TRUE, na.last = FALSE))
print(order(x, method = "radix", decreasing = TRUE, na.last = NA))
names(x) <- seq_along(x)
print(sort(x))
print(sort(x, method = "radix"))
print(sort.list(x))
print(sort.list(x, method = "radix", decreasing = TRUE))
print(rank(x))
print(rank(x, ties.method = "min", na.last = "keep"))
print(rank(unname(x), ties.method = "first", na.last = FALSE))
print(xtfrm(c("b", "a", NA, "b")))
print(is.unsorted(c("a", "B", "b")))
print(is.unsorted(c("a", "b", "B")))
print(is.unsorted(c("a", "a"), strictly = TRUE))
# equal under the collator, different strings: the sort keeps an order
y <- c("e\u0301", "\u00e9", "f", "e\u0301", "\u00e9", "e")
print(sort(y) == "\u00e9")
print(order(y))
print(rank(y))
print(sort(c("\u00e9", "e\u0301", "\u00e9")) == "\u00e9")
print(.Internal(sort(c("b", NA, "a", "B"), FALSE)))
print(.Internal(sort(c("b", NA, "a", "B"), TRUE)))
