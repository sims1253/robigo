# sort() and order() of complex numbers: real part first, then imaginary
x <- c(1+2i, NA, 1-1i, -3+0i, 0+0i, 1+2i, complex(real = NaN, imaginary = 1), 2i, -2i)
print(sort(x))
print(sort(x, decreasing = TRUE))
print(sort(x, na.last = TRUE))
print(sort(x, na.last = FALSE))
print(order(x))
print(order(x, decreasing = TRUE))
print(order(x, na.last = NA))
print(sort.list(x))
print(rank(x))
print(rank(x, ties.method = "max"))
print(is.unsorted(c(1i, 2i, 1+0i)))
print(.Internal(sort(c(2+1i, 1+3i, 1+1i), TRUE)))
print(tryCatch(order(x, method = "radix"), error = function(e) conditionMessage(e)))
print(tryCatch(sort(x, method = "quick"), error = function(e) conditionMessage(e)))
