# sort() of doubles with NA, NaN, -0, Inf: placements and the order of
# ties (1/x tells -0 from 0)
x <- c(2.5, NaN, -0, Inf, NA, 0, -Inf, -1e-300, 1e300, 0, -0, NA, 3, NaN, -2.5)
show <- function(v) print(c(v, 1/v[!is.na(v) & v == 0]))
show(sort(x))
show(sort(x, decreasing = TRUE))
show(sort(x, na.last = TRUE))
show(sort(x, na.last = FALSE))
for (m in c("shell", "quick", "radix")) {
  show(sort(x, method = m))
  show(sort(x, method = m, decreasing = TRUE, na.last = TRUE))
  show(sort(x, method = m, na.last = FALSE))
}
print(order(x))
print(order(x, decreasing = TRUE))
print(order(x, na.last = FALSE))
print(order(x, na.last = NA))
print(order(x, method = "shell"))
print(order(x, method = "shell", decreasing = TRUE, na.last = FALSE))
print(order(x, method = "shell", na.last = NA))
print(sort.list(x))
print(sort.list(x, method = "quick", na.last = NA))
print(sort.list(x, method = "shell", decreasing = TRUE))
y <- c(b = 2, a = 1, c = NaN, d = -0, e = 0)
print(sort(y))
print(sort(y, method = "quick"))
print(sort(y, decreasing = TRUE, method = "shell"))
print(sort(c(3, 1, 2, 1), index.return = TRUE, method = "quick"))
print(sort(c(3, 1, 2, 1), partial = 2))
print(sort(c(10, 3, 7, 1, 8, 2, 9), partial = c(3, 5)))
s <- .Internal(sort(c(2, -0, 0, NaN, 1, -0), FALSE))
print(c(s, 1/s))
print(.Internal(sort(c(2, -0, 0, NA, 1, -0), TRUE)))
print(.Internal(qsort(c(3, 1, 2, -0, 0), TRUE)))
print(.Internal(psort(c(5, 1, 4, 2, 3), c(2L, 4L))))
print(is.unsorted(c(1, 2, 2)))
print(is.unsorted(c(1, 2, 2), strictly = TRUE))
print(is.unsorted(c(1, NaN, 2)))
print(is.unsorted(c(-0, 0), strictly = TRUE))
