# sort()'s and its internals' argument checks
e <- function(expr) print(tryCatch(expr, error = function(e) conditionMessage(e)))
e(sort(1:3, decreasing = NA))
e(sort(1:3, decreasing = c(TRUE, FALSE)))
e(sort(list(1, 2)))
e(sort(c(3, 1, 2), partial = 2, decreasing = TRUE))
e(sort(c(3, 1, 2), partial = NA))
e(sort(c(3, 1, 2), partial = 2, method = "radix"))
e(sort(c(3, NA, 2), index.return = TRUE, na.last = TRUE, method = "shell"))
e(sort.list(list(1, 2), method = "shell"))
e(sort.list(c("b", "a"), method = "quick"))
e(sort(as.raw(c(3, 1, 2))))
e(.Internal(sort(list(1), FALSE)))
e(.Internal(sort(1:3, NA)))
e(.Internal(order(TRUE, FALSE, 1:3, 1:2)))
e(.Internal(order(TRUE, FALSE, list(1))))
e(.Internal(psort(1:5, 7L)))
e(.Internal(psort(1:5, NA_integer_)))
e(.Internal(qsort(list(1), FALSE)))
e(.Internal(rank(list(1), 1L, "average")))
e(.Internal(radixsort(TRUE, FALSE, FALSE, TRUE, 1:3, 1:2)))
e(.Internal(radixsort(TRUE, c(FALSE, TRUE), FALSE, TRUE, 1:3)))
e(.Internal(radixsort(TRUE, FALSE, FALSE, TRUE, list(1))))
e(is.unsorted(list(1, 2)))
e(is.unsorted(1:3, strictly = NA))
e(.Internal(is.unsorted(1:3, NA, FALSE)))
e(.Internal(sorted_fpass(1:3, NA, TRUE)))
print(.Internal(sorted_fpass(1:3, FALSE, TRUE)))
print(.Internal(sorted_fpass(c(3, 2, 1), TRUE, TRUE)))
print(.Internal(sorted_fpass(c(1, NA, 2), FALSE, TRUE)))
