# sort(), order(), rank() and xtfrm() of factors: by the codes, the
# levels kept (an ordered factor stays ordered)
f <- factor(c("b", "a", NA, "c", "a", "b"), levels = c("c", "b", "a"))
print(sort(f))
print(sort(f, decreasing = TRUE))
print(sort(f, na.last = TRUE))
print(order(f))
print(order(f, decreasing = TRUE, na.last = FALSE))
print(order(f, method = "shell"))
print(rank(f))
print(rank(f, ties.method = "min", na.last = "keep"))
print(xtfrm(f))
print(sort.list(f))
o <- factor(c("lo", "hi", "mid", "lo"), levels = c("lo", "mid", "hi"), ordered = TRUE)
print(sort(o))
print(sort(o, decreasing = TRUE))
print(order(o, c(2, 1, 1, 1)))
print(is.unsorted(o))
print(levels(sort(factor(c("z", "y", "x")))))
print(nlevels(sort(f)))
print(tryCatch(sort(f, index.return = TRUE, method = "shell"), error = function(e) conditionMessage(e)))
