# order() with several keys: ties in later keys, decreasing (a vector for
# "radix"), na.last, and the two methods
a <- c(2L, 1L, 2L, NA, 1L, 2L, 1L, NA)
b <- c(3, 3, 1, 2, NaN, 1, 3, 0)
s <- c("x", "y", "x", "a", "b", "y", "a", NA)
print(order(a, b))
print(order(a, b, decreasing = TRUE))
print(order(a, b, na.last = FALSE))
print(order(a, b, na.last = NA))
print(order(a, b, method = "shell"))
print(order(a, b, method = "shell", decreasing = TRUE, na.last = FALSE))
print(order(a, b, method = "shell", na.last = NA))
print(order(a, b, decreasing = c(TRUE, FALSE), method = "radix"))
print(order(a, s, b))
print(order(a, s, b, method = "shell"))
print(order(s, a, method = "radix", decreasing = c(FALSE, TRUE)))
print(order(c(TRUE, FALSE, NA, TRUE), c(2, 1, 1, 1)))
print(order())
print(order(integer()))
print(order(c(1, 1, 1)))
print(order(c(3, 2, 1)))
print(order(c(3, 2, 2)))
print(order(c(NA, NA), na.last = NA))
print(order(c(NA, 1), na.last = NA, method = "radix"))
print(order(c(NA, 1), na.last = NA, method = "shell"))
print(order(1:3, c(NA, 2, 1), na.last = NA))
print(sort.list(c(2, 1, NA), na.last = NA))
print(sort.list(c("b", "a", NA), na.last = NA, method = "shell"))
print(tryCatch(order(1:3, 1:2), error = function(e) conditionMessage(e)))
print(tryCatch(order(1:3, 1:3, decreasing = c(TRUE, FALSE), method = "shell"), error = function(e) conditionMessage(e)))
print(tryCatch(order(1:3, method = "radix", decreasing = c(TRUE, FALSE)), error = function(e) conditionMessage(e)))
print(tryCatch(order(1:3, decreasing = NA, method = "radix"), error = function(e) conditionMessage(e)))
print(tryCatch(order(list(1, 2)), error = function(e) conditionMessage(e)))
print(tryCatch(order(c("\u00e9", "a"), method = "radix"), error = function(e) conditionMessage(e)))
print(tryCatch(order(1:2, method = "nope"), error = function(e) conditionMessage(e)))
