# .Internal(radixsort()) directly: grouping (ends, maxgrpn, doubles rounded
# off in the last two bytes), strings in appearance order, decreasing per
# key, NAs kept while grouping, and its checks
r <- function(...) .Internal(radixsort(...))
e <- function(expr) print(tryCatch(expr, error = function(e) conditionMessage(e)))
print(r(TRUE, FALSE, TRUE, TRUE, c(3L, 1L, 3L, 2L, 1L)))
print(r(TRUE, FALSE, TRUE, TRUE, c(1, 1 + 1e-15, 2, 1 + 1e-10, NA, 2)))
print(r(TRUE, FALSE, FALSE, TRUE, c(1, 1 + 1e-15, 2, 1 + 1e-10, NA, 2)))
print(r(FALSE, FALSE, TRUE, TRUE, c(2, NA, 1, NaN, 2)))
print(r(TRUE, FALSE, TRUE, FALSE, c("b", "a", "b", "c", "a")))
print(r(TRUE, c(FALSE, FALSE), TRUE, FALSE, c(1L, 1L, 2L, 1L), c("y", "x", "z", "y")))
print(r(TRUE, c(TRUE, FALSE), FALSE, TRUE, c(1L, 2L, 1L, 2L), c(4, 3, 2, 1)))
print(r(NA, c(FALSE, TRUE), FALSE, TRUE, c(1L, 1L, NA, 2L), c(NA, 2, 1, 1)))
print(r(TRUE, FALSE, FALSE, TRUE, integer()))
print(r(NA, FALSE, FALSE, TRUE, c(NA_integer_, NA_integer_)))
print(r(TRUE, FALSE, FALSE, TRUE))
print(r(TRUE, c(FALSE, FALSE), FALSE, TRUE, c(3, 1, 2), list(1, 2, 3)))
e(r(TRUE, c(FALSE, FALSE), FALSE, TRUE, c(1, 1, 2), list(1, 2, 3)))
e(r(TRUE, FALSE, FALSE, TRUE, 1i))
e(r(TRUE, FALSE, FALSE, TRUE, "\xff"))
e(r(TRUE, FALSE, NA, TRUE, 1:3))
e(r(TRUE, FALSE, FALSE, TRUE, NULL))
e(r(TRUE, c(TRUE, NA), FALSE, TRUE, 1:3, 1:3))
print(r(TRUE, FALSE, FALSE, TRUE, c("b", "é", "a", "B")))
print(r(TRUE, TRUE, FALSE, TRUE, c(3L, 2L, 1L)))
print(r(TRUE, FALSE, FALSE, TRUE, c(-0, 0, -0, 0)))
