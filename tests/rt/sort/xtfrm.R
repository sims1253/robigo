# xtfrm(): numbers as they are, factors as their codes, the rest by rank
print(xtfrm(c(3, 1, NA, 2)))
print(xtfrm(c(b = 2L, a = 1L)))
print(xtfrm(c(TRUE, FALSE)))
print(xtfrm(c("b", "a", NA, "c", "a")))
print(xtfrm(c(2+1i, 1+0i)))
print(xtfrm(I(c(3, 1, 2))))
x <- structure(c(3, 1, 2), class = "myclass")
print(xtfrm(x))
xtfrm.myclass <- function(x) -unclass(x)
print(xtfrm(x))
print(order(x))
print(sort(x))
print(tryCatch(xtfrm(list(1, 2)), error = function(e) conditionMessage(e)))
