# make.names, make.unique (character.c, unique.c), tolower/toupper
err <- function(expr) tryCatch(expr, error = function(e) conditionMessage(e))

# make.names
print(make.names(c("a b", "1x", ".1", "._", "a_b", "", NA, "if", "TRUE", "...", "..1",
                   ".", "_x", "a.b.c", "x-y", "NA_integer_", "function", "Inf")))
print(make.names(c("é x", "日本", "αβ", "x²", "٣a", "a٣", "é", "€uro", "ǅ")))
print(make.names("a_b", allow_ = FALSE))
print(make.names(c("a", "a", "a.1"), unique = TRUE))
print(make.names(1:3))
print(make.names(character()))
print(Encoding(make.names(c("é", "a"))))
print(err(.Internal(make.names(1, TRUE))))
print(err(.Internal(make.names("a", NA))))
print(err(make.names("\xff")))
print(err(make.names("a\xff")))
print(err(make.names(c("ok", ".\xff"))))
print(err(make.names("\xe2\x82")))

# make.unique
print(make.unique(c("a", "a", "a")))
print(make.unique(c("a", "a", "a.1")))
print(make.unique(c("a", "a.1", "a")))
print(make.unique(c("b", "a", "a", "b", "a")))
print(make.unique(c(NA, NA, "NA")))
print(make.unique(c("a", "a"), sep = "_"))
print(make.unique(c("a", "a"), NA_character_))
print(make.unique(c("\xc3\xa9", "\xc3\xa9")))
print(make.unique(c("é", "é", "é")))
print(Encoding(make.unique(c("é", "é"))))
print(make.unique(character()))
print(make.unique("a"))
print(make.unique(c("", "", "")))
print(err(make.unique(1)))
print(err(make.unique("a", c("_", "-"))))
print(err(make.unique("a", 1)))

# tolower, toupper
print(toupper(c("abc", NA, "ÄéÿßΣσς", "ǆ", "ﬃ", "ı")))
print(tolower(c("ÀÉÎ", "ΣΑΣ", "İ", "ǅ", "ABC")))
print(toupper(1:3))
print(casefold("Ab", upper = TRUE))
print(casefold("Ab"))
x <- c(a = "x", b = "Y")
print(toupper(x))
m <- matrix(c("a", "b", "c", "d"), 2)
u <- toupper(m); dim(u); as.vector(u)
print(attributes(toupper(structure("a", class = "foo", k = 1))))
print(Encoding(toupper(c("\xc3\xa9", "é", "a"))))
print(toupper(c("\xc3\xa9", "é")))
print(err(toupper("\xff")))
print(err(tolower(c("a", "b\xc3"))))
print(err(.Internal(toupper(1))))
print(toupper(character()))
