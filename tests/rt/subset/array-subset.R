# ArraySubset: x[i, j, k, ...] of arrays of three or more extents
show <- function(expr) tryCatch(print(expr), error = function(e) print(e), warning = function(w) print(w))
a <- array(1:24, c(2, 3, 4))
show(a[2, 3, 4])
show(a[, , 1])
show(a[1, , ])
show(a[, 2, ])
show(a[2, 2, ])
show(a[1, , , drop = FALSE])
show(a[, , 2, drop = FALSE])
show(a[-1, c(TRUE, FALSE, TRUE), 2:3])
show(a[c(1, NA), 1, 1])
show(a[NA, 1, 1])
show(a[c(1, NA), 2, 2:3])
show(a[0, , ])
show(a[, 0, 1])
show(a[, 0, 1, drop = FALSE])
show(dim(a[, , 0]))
show(a[, , ])
dimnames(a) <- list(c("a", "b"), c("x", "y", "z"), c("p", "q", "r", "s"))
show(a["b", , ])
show(a[, "y", c("s", "p")])
show(a["a", "z", "q"])
show(a["a", "z", "q", drop = FALSE])
show(a[, , "r"])
show(a[c("a", NA), "x", 1:2])
names(dimnames(a)) <- c("A", "B", "C")
show(a[1, 2:3, 1:2])
show(a[1, 2, ])
show(a[, , 1, drop = FALSE])
show(dimnames(a[, 0, ]))
show(dimnames(a[, 0, , drop = FALSE]))
dimnames(a) <- list(NULL, c("x", "y", "z"), NULL)
show(a[2, , 3])
show(a[, "x", 1])
show(a[1, 1, 1])
# the names of the dim
b <- array(1:8, c(u = 2L, v = 2L, w = 2L))
show(attributes(b[, 1, ]))
show(attributes(b[, , 1, drop = FALSE]))
show(attributes(b[1, 1, ]))
# four extents, other types
c4 <- array(letters[1:16], c(2, 2, 2, 2))
show(c4[2, 1, 2, ])
show(c4[, , 1, 1])
show(c4[2, 2, 2, 2])
l <- array(as.list(1:8), c(2, 2, 2))
show(l[1, 2, ])
show(array(as.raw(1:8), c(2, 2, 2))[2, , 2])
show(array(c(TRUE, FALSE), c(2, 2, 2))[, 1, ])
show(array(1:8 + 0i, c(2, 2, 2))[NA, 1, 1])
show(array(1:8 * 1.5, c(2, 2, 2))[2, , , drop = TRUE])
# errors
