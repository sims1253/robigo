show(a[3, 1, 1])
show(a[1, 1, 5])
show(a[1, "w", 1])
show(array(1:8, c(2, 2, 2))[1, 1, "a"])
show(a[1, c(TRUE, TRUE, TRUE, TRUE), 1])
show(a[c(-1, 2), 1, 1])
show(a[1, list(), 1])
