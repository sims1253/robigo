# drop() and DropDims
# (robigo-rt does not print matrices yet: an array is shown as its
# attributes and its elements)
show <- function(expr) tryCatch({
    v <- expr
    if (is.array(v)) { print(attributes(v)); attributes(v) <- NULL; print(v) } else print(v)
}, error = function(e) print(e), warning = function(w) print(w))
show(drop(matrix(1:3, 1)))
show(drop(matrix(1:3, 3)))
show(drop(matrix(1:4, 2)))
show(drop(array(5L, c(1, 1, 1))))
show(drop(1:3))
show(drop(NULL))
show(drop(array(1:6, c(1, 2, 3))))
show(drop(array(1:6, c(1, 2, 1, 3, 1))))
x <- array(1:6, c(1, 2, 3), dimnames = list("a", c("b", "c"), c("d", "e", "f")))
show(drop(x))
names(dimnames(x)) <- c("A", "B", "C")
show(drop(x))
show(attributes(drop(x)))
y <- array(1:2, c(1, 2, 1), dimnames = list("a", NULL, "z"))
show(drop(y))
show(attributes(drop(y)))
z <- array(7, c(1, 1), dimnames = list("r", "s"))
show(drop(z))
z1 <- array(7, c(1, 1), dimnames = list(NULL, "s"))
show(drop(z1))
w <- array(1:4, c(u = 1L, v = 4L, w = 1L))
show(attributes(drop(w)))
w2 <- array(1:8, c(u = 2L, v = 1L, w = 4L))
show(attributes(drop(w2)))
k <- structure(matrix(1:3, 1), class = "bar", other = 1)
show(attributes(drop(k)))
e <- matrix(numeric(0), 1, 0)
show(drop(e))
show(attributes(drop(array(1:3, c(1, 3), dimnames = list("x", NULL)))))
