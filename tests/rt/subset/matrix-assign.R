# x[i, j] <- x: the RHS is copied first
p <- matrix(1:4, 2)
p[2:1, ] <- p; show(p)
permute <- structure(c(3L, 1L, 2L), dim = c(3, 1))
permute[permute, 1] <- 1:3
show(as.vector(permute))
# attributes are kept
a <- structure(matrix(1:4, 2), class = "foo", extra = 1)
a <- unclass(a); a[1, 1] <- 0L; show(attributes(a))
# in a function, the caller's copy is untouched
f <- function(x) { x[1, 1] <- -1L; x }
mm <- matrix(1:4, 2); show(f(mm)); show(mm)
