# MatrixAssign: x[i, j] <- y
# (robigo-rt does not print matrices yet: an array is shown as its
# attributes and its elements)
show <- function(expr) tryCatch({
    v <- expr
    if (is.array(v)) { print(attributes(v)); attributes(v) <- NULL; print(v) } else print(v)
}, error = function(e) print(e), warning = function(w) print(w))
# (robigo-rt has no cbind/rbind yet: these build the same matrices)
cb <- function(...) { a <- list(...); matrix(unlist(a), ncol = length(a)) }
rb <- function(...) { a <- list(...); matrix(unlist(a), nrow = length(a), byrow = TRUE) }
m <- matrix(1:12, 3, 4)
m[2, 3] <- 0L; show(m)
m[, 1] <- c(7L, 8L, 9L); show(m)
m[1, ] <- 1:2; show(m)
m[-1, c(TRUE, FALSE)] <- 100L; show(m)
m[0, ] <- 5L; show(m)
m[2, 2] <- 2.5; show(m)
m[3, 4] <- "z"; show(m)
m <- matrix(1:6, 2)
m[1, 1] <- TRUE; show(m)
m[NA, 1] <- 0L; show(m)
m[c(1, NA), 2] <- 9L; show(m)
m[2, ] <- 1i; show(m)
dimnames(m) <- list(c("a", "b"), c("x", "y", "z"))
m["a", "y"] <- 0; show(m)
m[, c("z", "x")] <- c(-1, -2); show(m)
m["b", ] <- NA; show(m)
l <- matrix(list(1, 2, 3, 4), 2)
l[1, 2] <- list("a"); show(l)
l[2, ] <- 0; show(l)
l[, 1] <- list(NULL); show(l)
r <- matrix(as.raw(1:4), 2)
r[2, 2] <- as.raw(255); show(r)
cm <- matrix(c("a", "b", "c", "d"), 2)
cm[1, ] <- c(TRUE, FALSE); show(cm)
cm[2, 2] <- 3.5; show(cm)
lg <- matrix(c(TRUE, FALSE, NA, TRUE), 2)
lg[1, 1] <- 2L; show(lg)
lg <- matrix(c(TRUE, FALSE, NA, TRUE), 2)
lg[2, ] <- 1.5; show(lg)
z <- matrix(1:4 + 0i, 2)
z[1, 1] <- NA_real_; show(z)
