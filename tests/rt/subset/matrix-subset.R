# MatrixSubset: x[i, j] by every kind of subscript, with dimnames, drop
show <- function(expr) tryCatch(print(expr), error = function(e) print(e), warning = function(w) print(w))
m <- matrix(1:12, 3, 4)
show(m[2, 3])
show(m[2, ])
show(m[, 3])
show(m[2, , drop = FALSE])
show(m[, 3, drop = FALSE])
show(m[-1, ])
show(m[c(TRUE, FALSE, TRUE), ])
show(m[c(TRUE, FALSE), c(1, 1, 2)])
show(m[0, ])
show(m[, 0])
show(m[0, 0])
show(m[NA, 1])
show(m[c(1, NA), 2:3])
show(m[NA_integer_, ])
show(m[2.7, 1.2])
show(m[c(-1, 0), ])
show(m[NULL, 1])
show(m[, ])
show(m[3, 4, drop = NA])
show(m[1, 2:3, drop = 0])
dimnames(m) <- list(c("a", "b", "c"), c("w", "x", "y", "z"))
show(m["b", ])
show(m[, c("z", "w")])
show(m[c("a", NA), "x"])
show(m["b", "y"])
show(m["b", "y", drop = FALSE])
show(m[-2, c(TRUE, FALSE)])
show(m[2, , drop = FALSE])
names(dimnames(m)) <- c("rows", "cols")
show(m[1:2, "x"])
show(m[1:2, "x", drop = FALSE])
show(m[2, 3])
show(m[c(2, 2), ])
dimnames(m) <- list(NULL, c("w", "x", "y", "z"))
show(m[2, ])
show(m[2, 1])
show(m[, "y"])
dimnames(m) <- list(c("a", "b", "c"), NULL)
show(m[, 2])
show(m[1, 1])
# the names of the dim are kept
d <- matrix(1:6, 2)
dim(d) <- c(r = 2L, c = 3L)
show(attributes(d[, 2:3]))
show(attributes(d[1, ]))
# other types
show(matrix(c("a", "b", "c", "d"), 2)[2, ])
show(matrix(list(1, "a", TRUE, NULL), 2)[, 2])
show(matrix(list(1, "a", TRUE, NULL), 2)[1, , drop = FALSE])
show(matrix(as.raw(1:4), 2)[2, 2])
show(matrix(as.raw(1:4), 2)[c(1, NA), 2])
show(matrix(c(1i, 2, 3, 4i), 2)[NA, 1])
show(matrix(c(TRUE, NA, FALSE, TRUE), 2)[c(2, NA), ])
show(matrix(c("a", "b"), 1)[1, c(NA, 2)])
# attributes other than dim and dimnames are dropped
a <- structure(matrix(1:4, 2), class = "foo", extra = "e")
show(attributes(unclass(a)[1:2, 1:2]))
show(attributes(.subset(a, 1:2, 1)))
# errors
show(m[1, 2, 3])
show(m[4, 1])
show(m[1, 5])
show(m[c(1, 7), ])
show(m[, -9:-8])
show(m[-1, 1:2][c(-1, 1), ])
show(m["d", ])
show(matrix(1:4, 2)["a", 1])
show(m[c(TRUE, FALSE, TRUE, TRUE), ])
show(m[list(1), 1])
show(m[1, quote(a)])
show(m[1i, 1])
show(m[c(-1, 1), ])
show(m[c(-1, NA), ])
show(m[2e10, 1])
